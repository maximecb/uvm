//! Code generation: LLVM IR module -> UVM assembly text.
//!
//! Strategy (correctness-first, see plan.md):
//! - Each instruction result gets a local slot; parameters are read via
//!   `get_arg`. Lowering an instruction = push operands, emit the typed op,
//!   `set_local` the result. The operand stack is empty between instructions.
//! - Integer values are kept zero-extended to their width in a 64-bit slot.
//!   Use natural-width ops (`_u32`/`_i32` for width <= 32, `_u64`/`_i64` for
//!   64). After a sub-32-bit op, truncate to re-establish the invariant; for
//!   signed sub-32-bit ops, sign-extend operands first.

use rustc_hash::{FxHashMap as HashMap, FxHashSet as HashSet};

use crate::ast::*;
use crate::layout::Layout;

/// Size in bytes of the main thread's software stack (for `alloca` and
/// address-taken locals), emitted as a single `.zero` buffer (`__main_stack__`).
/// The program entry installs its base into STACK_TLS_SLOT before running main.
/// Other threads bring their own stack: <pthread.h> threads get a private one
/// from the trampoline; a raw `thread_spawn` thread gets none, so its first
/// alloca faults (SP is 0, an unmapped low address) — by design, use
/// pthread_create for threads that run alloca-bearing code.
const STACK_ALLOC_SIZE: u64 = 8 * 1024 * 1024;

/// Thread-local slot (thread_get/thread_set index) holding the thread's software
/// stack pointer (top of its alloca region). It is installed for the main thread
/// by the program entry and for pthread threads by <pthread.h>'s frame-free
/// trampoline (__uvclang_thread_start). A thread that never sets it has SP 0 and
/// faults on its first alloca — there is no shared fallback stack.
const STACK_TLS_SLOT: u8 = 0;

pub struct Codegen<'a>
{
    module: &'a Module,
    layout: Layout<'a>,
    out: String,
    /// Names of functions with a body in this module. A direct call to any
    /// other `@name` (a bare `declare`, an unimplemented libc/intrinsic helper)
    /// is rejected rather than emitting a dangling label reference.
    defined_fns: HashSet<&'a str>,
    /// Counter for generating unique labels (branch edges, select, switch).
    label_counter: usize,
    /// Constant-expression values that can't be a static directive, initialized
    /// by code at program startup: (global label, byte offset, expression).
    runtime_inits: Vec<(String, u64, ConstExpr)>,
    /// Emitted lines for the current scope (one function, or the shared
    /// preamble), pending flush to `out`. Buffering per scope lets a peephole
    /// pass collapse single-use `set_local`/`get_local` round-trips before the
    /// lines are committed — see `flush_scope` / `peephole_locals`.
    buf: Vec<String>,
}

/// Per-function lowering context.
struct FnCtx<'f>
{
    name: String,
    /// Parameter name -> argument index.
    params: HashMap<&'f str, usize>,
    /// Instruction-result name -> local slot index.
    slots: HashMap<&'f str, usize>,
    /// Block label -> basic block (for resolving phi edges).
    blocks: HashMap<&'f str, &'f BasicBlock>,
    /// Alloca result name -> byte offset within the stack-alloc frame.
    alloca_offsets: HashMap<&'f str, u64>,
    /// Total size of the *static* part of this function's stack-alloc frame (0
    /// if it has no constant-count allocas; a dynamic alloca can still exist).
    frame_size: u64,
    /// Whether this function establishes a stack-alloc frame at all: true if it
    /// has any static frame bytes or any dynamic alloca. Gates the prologue that
    /// saves the base pointer and the epilogue that resets the stack pointer.
    has_frame: bool,
    /// Local slot holding the saved stack-alloc pointer (valid iff has_frame).
    bp_slot: usize,
    /// Number of fixed (named) parameters — the `gp_offset` seed for va_start.
    num_params: usize,
    /// Scratch slots (buffer-base, loop-index) used by `llvm.va_start` to build
    /// the x86_64 va_list register-save area. `None` unless the function uses it.
    va_scratch: Option<(usize, usize)>,
}

impl<'a> Codegen<'a>
{
    pub fn new(module: &'a Module) -> Self
    {
        let defined_fns = module
            .functions
            .iter()
            .filter(|f| !f.is_decl())
            .map(|f| f.name.as_str())
            .collect();
        Codegen {
            module,
            layout: Layout::new(module),
            out: String::new(),
            defined_fns,
            label_counter: 0,
            runtime_inits: vec![],
            buf: vec![],
        }
    }

    pub fn generate(mut self) -> Result<String, String>
    {
        self.line("#");
        self.line("# Generated by the uvclang compiler (LLVM IR -> UVM).");
        self.line("#");
        self.line("");
        self.gen_data()?;
        self.gen_code()?;
        self.flush_scope(); // commit anything left in the final scope
        Ok(self.out)
    }

    fn gen_data(&mut self) -> Result<(), String>
    {
        self.line(".data;");
        self.line("");

        let module = self.module;
        for g in &module.globals {
            self.emit_global(g)?;
        }

        // The main thread's software stack (alloca region). Its base address is
        // installed into the stack-pointer TLS slot by the program entry; other
        // threads bring their own stack (see STACK_TLS_SLOT).
        self.line(".align 8;");
        self.line("__main_stack__:");
        self.line(&format!(".zero {};", STACK_ALLOC_SIZE));
        self.line("");
        Ok(())
    }

    fn gen_code(&mut self) -> Result<(), String>
    {
        self.line(".code;");

        // Install the main thread's software stack pointer before running any
        // guest code (const-expr init or main), which may use `alloca`. This is
        // frame-free (a single thread_set), so it needs no stack itself.
        self.line("# install the main thread's alloca stack pointer");
        self.line("push __main_stack__;");
        self.line(&format!("thread_set {};", STACK_TLS_SLOT));
        self.line("");

        // Initialize globals whose initializer is a constant expression.
        if !self.runtime_inits.is_empty() {
            self.line("# initialize const-expression globals");
            let inits = std::mem::take(&mut self.runtime_inits);
            for (label, off, ce) in &inits {
                self.line(&format!("push {};", label));
                if *off != 0 {
                    self.push_int(*off as i128, 64);
                    self.line("add_u64;");
                }
                self.emit_const_expr(ce)?;
                self.line("store_u64;");
            }
            self.line("");
        }

        // How many parameters does main declare? A plain `int main(void)` takes
        // none; `int main(int argc, char** argv)` takes two. We only build the
        // argc/argv vector when main actually asks for it, so the common no-arg
        // case (and every existing test) keeps emitting a bare `call main, 0`.
        let main_argc = self.module.functions.iter()
            .find(|f| f.name == "main" && !f.is_decl())
            .map_or(0, |f| f.params.len());

        self.line("# program entry: run main, then halt with its return value");
        if main_argc == 0 {
            self.line("call main, 0;");
            self.line("ret;");
        } else {
            // main wants argc/argv: build the vector in a helper (which needs a
            // frame for its locals) and forward main's return value up.
            self.line("call __uvclang_start, 0;");
            self.line("ret;");
        }
        self.line("");

        if main_argc != 0 {
            self.emit_start(main_argc)?;
        }

        self.emit_thread_trampoline();
        self.flush_scope(); // preamble (entry, __uvclang_start, trampoline) is one scope

        // Copy out the module reference so the loop doesn't borrow `self`.
        let module = self.module;
        for f in &module.functions {
            if !f.is_decl() {
                self.gen_function(f)?;
                self.flush_scope(); // each function's slots are counted on their own
            }
        }
        Ok(())
    }

    /// Emit the frame-free thread entry trampoline referenced by <pthread.h>.
    ///
    /// A newly spawned thread starts with no stack (thread-local slot
    /// STACK_TLS_SLOT == 0), so the very first alloca-bearing function it entered
    /// would fault. To give pthread-created threads a private stack, pthread_create
    /// hands thread_spawn this trampoline instead of the user's start routine,
    /// passing a control block:
    ///
    ///     struct { void* stack; void* (*start)(void*); void* arg; u64 tid; }
    ///
    /// The trampoline installs the block's `stack` as the thread-local stack
    /// pointer *before* calling `start`, so every frame `start` allocates lands
    /// on the private stack. It must itself use no `alloca`s (hence it is
    /// emitted by hand rather than compiled from C): it only reads arg 0 and
    /// manipulates the operand stack, so it needs no frame of its own and does
    /// not depend on a stack pointer being set up first.
    fn emit_thread_trampoline(&mut self)
    {
        self.line("# frame-free thread entry trampoline for <pthread.h>");
        self.line("# arg 0 = control block { stack@0, start@8, arg@16, tid@24 }");
        self.line("__uvclang_thread_start:");
        // Install the private stack pointer: sp = cb->stack.
        self.line("get_arg 0;");
        self.line("load_u64;");                              // cb->stack
        self.line(&format!("thread_set {};", STACK_TLS_SLOT));
        // Call start(arg): push arg, then the function pointer, then call_fp.
        self.line("get_arg 0;");
        self.line("push 16;");
        self.line("add_u64;");
        self.line("load_u64;");                              // cb->arg
        self.line("get_arg 0;");
        self.line("push 8;");
        self.line("add_u64;");
        self.line("load_u64;");                              // cb->start
        self.line("call_fp 1;");                             // start(arg) -> result
        self.line("ret;");                                   // thread_join sees this
        self.line("");
    }

    /// Emit `__uvclang_start`, the entry helper that constructs argc/argv from
    /// the host's command-line arguments and calls `main(argc, argv)`.
    ///
    /// The host exposes the arguments through two syscalls: `cmd_argc` returns
    /// the count, and `cmd_get_arg(idx, dst, dst_len)` copies argument `idx`
    /// (NUL-terminated) into a guest buffer, returning the argument's byte
    /// length excluding the NUL — so calling it with `dst_len == 0` queries the
    /// size to allocate. There is no shared "argv already in memory": we must
    /// allocate space and copy each string in ourselves.
    ///
    /// Rather than depend on the C `malloc`/`memcpy` being linked, we bump the
    /// guest heap directly with `vm_grow_heap` (whose argument is the desired
    /// absolute heap size; it returns the new, page-rounded size). Each block we
    /// carve is `[old_heap_size, old_heap_size + n)`. This is safe to interleave
    /// with the C allocator, which also grabs memory only via `vm_grow_heap` and
    /// initializes its base lazily above whatever the heap end is at that point.
    /// The copy itself is done by `cmd_get_arg`, so no `memcpy` is needed.
    ///
    /// Layout built:
    ///   argv = alloc((argc + 1) * 8)      // NULL-terminated pointer array
    ///   for i in 0..argc:
    ///       len     = cmd_get_arg(i, 0, 0)
    ///       argv[i] = alloc(len + 1); cmd_get_arg(i, argv[i], len + 1)
    ///   argv[argc] = NULL
    ///   return main(argc[, argv])
    ///
    /// `main` is called with `main_argc` arguments (1 for `int main(int argc)`,
    /// 2 for the usual `int main(int argc, char** argv)`); anything beyond argv
    /// is unsupported.
    fn emit_start(&mut self, main_argc: usize) -> Result<(), String>
    {
        if main_argc > 2 {
            return Err(format!(
                "main declares {} parameters; only (argc, argv) is supported", main_argc));
        }

        // Local slots used by the builder.
        const N: &str = "0";      // argc
        const ARGV: &str = "1";   // pointer array base
        const I: &str = "2";      // loop counter
        const LEN: &str = "3";    // current argument length
        const S: &str = "4";      // current argument string pointer

        let l_loop = self.fresh_label("start_loop");
        let l_done = self.fresh_label("start_done");

        self.line("# entry helper: build argc/argv from the host, then call main");
        self.line("__uvclang_start:");
        self.line("push_0n 5;");

        // argc = cmd_argc()
        self.line("syscall cmd_argc;");
        self.line(&format!("set_local {};", N));

        // argv = alloc((argc + 1) * 8): grab [base, base + size) off the heap.
        self.line("syscall vm_heap_size;");                  // [base]
        self.line("dup;");                                   // [base, base]
        self.line(&format!("get_local {};", N));
        self.line("push 1;");
        self.line("add_u64;");
        self.line("push 8;");
        self.line("mul_u64;");                               // [base, base, size]
        self.line("add_u64;");                               // [base, base+size]
        self.line("syscall vm_grow_heap;");                  // [base, new_heap_size]
        self.line("pop;");                                   // [base]
        self.line(&format!("set_local {};", ARGV));

        // for (i = 0; i < argc; i++)
        self.line("push 0;");
        self.line(&format!("set_local {};", I));
        self.line(&format!("{}:", l_loop));
        self.line(&format!("get_local {};", I));
        self.line(&format!("get_local {};", N));
        self.line("lt_u64;");
        self.line(&format!("jz {};", l_done));

        // len = cmd_get_arg(i, 0, 0)  (query the size, no copy)
        self.line(&format!("get_local {};", I));
        self.line("push 0;");
        self.line("push 0;");
        self.line("syscall cmd_get_arg;");
        self.line(&format!("set_local {};", LEN));

        // s = alloc(len + 1)
        self.line("syscall vm_heap_size;");                  // [base]
        self.line("dup;");                                   // [base, base]
        self.line(&format!("get_local {};", LEN));
        self.line("push 1;");
        self.line("add_u64;");                               // [base, base, len+1]
        self.line("add_u64;");                               // [base, base+len+1]
        self.line("syscall vm_grow_heap;");                  // [base, new_heap_size]
        self.line("pop;");                                   // [base]
        self.line(&format!("set_local {};", S));

        // cmd_get_arg(i, s, len + 1)  (copy the NUL-terminated string in)
        self.line(&format!("get_local {};", I));
        self.line(&format!("get_local {};", S));
        self.line(&format!("get_local {};", LEN));
        self.line("push 1;");
        self.line("add_u64;");
        self.line("syscall cmd_get_arg;");
        self.line("pop;");                                   // discard returned length

        // argv[i] = s  (store: push address, then value)
        self.line(&format!("get_local {};", ARGV));
        self.line(&format!("get_local {};", I));
        self.line("push 8;");
        self.line("mul_u64;");
        self.line("add_u64;");                               // &argv[i]
        self.line(&format!("get_local {};", S));
        self.line("store_u64;");

        // i++
        self.line(&format!("get_local {};", I));
        self.line("push 1;");
        self.line("add_u64;");
        self.line(&format!("set_local {};", I));
        self.line(&format!("jmp {};", l_loop));

        self.line(&format!("{}:", l_done));

        // argv[argc] = NULL
        self.line(&format!("get_local {};", ARGV));
        self.line(&format!("get_local {};", N));
        self.line("push 8;");
        self.line("mul_u64;");
        self.line("add_u64;");                               // &argv[argc]
        self.line("push 0;");
        self.line("store_u64;");

        // return main(argc[, argv])
        self.line(&format!("get_local {};", N));             // argc
        if main_argc >= 2 {
            self.line(&format!("get_local {};", ARGV));      // argv
        }
        self.line(&format!("call main, {};", main_argc));
        self.line("ret;");
        self.line("");

        Ok(())
    }

    fn gen_function(&mut self, f: &'a Function) -> Result<(), String>
    {
        // Build the lowering context: parameter and result-slot maps.
        let mut params = HashMap::default();
        for (i, p) in f.params.iter().enumerate() {
            if let Some(name) = &p.name {
                params.insert(name.as_str(), i);
            }
        }
        let mut slots = HashMap::default();
        let mut num_slots = 0usize;
        let mut blocks = HashMap::default();
        for bb in &f.blocks {
            blocks.insert(bb.label.as_str(), bb);
            for inst in &bb.insts {
                if let Some(dest) = &inst.dest {
                    slots.insert(dest.as_str(), num_slots);
                    // A cmpxchg result and a `*.with.overflow` intrinsic result
                    // are both the aggregate { value, i1 }: reserve a second slot
                    // right after the first so extractvalue can read field 0
                    // (value) at `slot` and field 1 (flag) at `slot + 1`.
                    let two = matches!(inst.kind, InstKind::Cmpxchg { .. })
                        || matches!(&inst.kind,
                            InstKind::Call { callee: Value::Global(n), .. }
                                if n.contains(".with.overflow."));
                    num_slots += if two { 2 } else { 1 };
                }
            }
        }
        // Lay out the stack-alloc frame: assign each *static* (constant-count)
        // alloca a byte offset. A dynamic (runtime-count) alloca is not
        // pre-laid-out; it bumps the software stack pointer at its point of
        // execution (see gen_dynamic_alloca) and is reclaimed by the same frame
        // teardown on return. We only note that one is present here.
        let mut alloca_offsets = HashMap::default();
        let mut frame_off = 0u64;
        let mut has_dynamic_alloca = false;
        for bb in &f.blocks {
            for inst in &bb.insts {
                if let InstKind::Alloca { ty, count, .. } = &inst.kind {
                    let dest = inst.dest.as_deref().ok_or("alloca without result")?;
                    let n: u64 = match count {
                        None => 1,
                        Some(tv) => match &tv.val {
                            Value::Int(c) => *c as u64,
                            // Non-constant count: lower at runtime, not here.
                            _ => {
                                has_dynamic_alloca = true;
                                continue;
                            }
                        },
                    };
                    frame_off = align_up(frame_off, self.layout.align_of(ty));
                    alloca_offsets.insert(dest, frame_off);
                    frame_off += self.layout.size_of(ty) * n;
                }
            }
        }
        let frame_size = align_up(frame_off, 8);
        // A function needs a stack-alloc frame (a saved base pointer, plus the
        // teardown that resets the stack pointer on return) if it has any static
        // frame bytes OR any dynamic alloca whose region must be reclaimed.
        let has_frame = frame_size > 0 || has_dynamic_alloca;
        let bp_slot = num_slots;
        let frame_slots = if has_frame { 1 } else { 0 };

        // A function that calls `llvm.va_start` needs two scratch local slots to
        // build the x86_64 va_list register-save area (see gen_va_start). They
        // sit just past the bp slot.
        let has_va_start = f.blocks.iter().flat_map(|bb| &bb.insts).any(|inst| {
            matches!(&inst.kind,
                InstKind::Call { callee: Value::Global(n), .. } if n.starts_with("llvm.va_start"))
        });
        let (va_scratch, va_slots) = if has_va_start {
            let base = num_slots + frame_slots;
            (Some((base, base + 1)), 2)
        } else {
            (None, 0)
        };
        let total_slots = num_slots + frame_slots + va_slots;

        let ctx = FnCtx {
            name: sanitize(&f.name),
            params,
            slots,
            blocks,
            alloca_offsets,
            frame_size,
            has_frame,
            bp_slot,
            num_params: f.params.len(),
            va_scratch,
        };

        self.line(&format!("# {} @{}({} params)", type_str(&f.ret_ty), f.name, f.params.len()));
        self.line(&format!("{}:", ctx.name));

        // Reserve local slots (push_0n takes a u16 operand).
        if total_slots > 0 {
            if total_slots > u16::MAX as usize {
                return Err(format!("function {} needs {} locals (> 65535)", f.name, total_slots));
            }
            self.line(&format!("push_0n {};", total_slots));
        }

        // Enter the stack-alloc frame: save the thread's software stack pointer
        // (thread-local slot STACK_TLS_SLOT) as the frame base (bp) and advance
        // it by frame_size. With only dynamic allocas, frame_size is 0: this just
        // records bp (the reset target) and leaves the stack pointer where it is.
        if ctx.has_frame {
            self.line(&format!("thread_get {};", STACK_TLS_SLOT));
            self.line("dup;");
            self.line(&format!("set_local {};", ctx.bp_slot));
            self.line(&format!("push {};", frame_size));
            self.line("add_u64;");
            self.line(&format!("thread_set {};", STACK_TLS_SLOT));
        }

        for bb in &f.blocks {
            self.line(&format!("{}:", block_label(&ctx.name, &bb.label)));
            for inst in &bb.insts {
                self.gen_inst(&ctx, inst)?;
            }
            self.gen_term(&ctx, &bb.label, &bb.term)?;
        }

        self.line("");
        Ok(())
    }

    // -- instructions ---------------------------------------------------------

    fn gen_inst(&mut self, ctx: &FnCtx, inst: &Inst) -> Result<(), String>
    {
        match &inst.kind {
            InstKind::Bin { op, ty, lhs, rhs } => {
                self.gen_bin(ctx, *op, ty, lhs, rhs)?;
                self.store_dest(ctx, inst.dest.as_deref())?;
            }
            InstKind::FBin { op, ty, lhs, rhs } => {
                self.gen_fbin(ctx, *op, ty, lhs, rhs)?;
                self.store_dest(ctx, inst.dest.as_deref())?;
            }
            InstKind::FNeg { ty, val } => {
                self.gen_fneg(ctx, ty, val)?;
                self.store_dest(ctx, inst.dest.as_deref())?;
            }
            InstKind::FCmp { pred, ty, lhs, rhs } => {
                self.gen_fcmp(ctx, *pred, ty, lhs, rhs)?;
                self.store_dest(ctx, inst.dest.as_deref())?;
            }
            InstKind::Conv { op, from_ty, val, to_ty } => {
                self.gen_conv(ctx, *op, from_ty, val, to_ty)?;
                self.store_dest(ctx, inst.dest.as_deref())?;
            }
            InstKind::ICmp { pred, ty, lhs, rhs } => {
                self.gen_icmp(ctx, *pred, ty, lhs, rhs)?;
                self.store_dest(ctx, inst.dest.as_deref())?;
            }
            InstKind::Select { cond, ty, tval, fval } => {
                self.gen_select(ctx, cond, ty, tval, fval)?;
                self.store_dest(ctx, inst.dest.as_deref())?;
            }
            InstKind::Load { ty, ptr, .. } => {
                let bits = self.scalar_bits(ty)?;
                self.push_value(ctx, ptr, 64)?;
                self.line(&format!("load_u{};", bits));
                self.store_dest(ctx, inst.dest.as_deref())?;
            }
            InstKind::Store { ty, val, ptr, .. } => {
                let bits = self.scalar_bits(ty)?;
                self.push_value(ctx, ptr, 64)?; // address (popped second by store)
                self.push_value(ctx, val, scalar_width(ty)?)?; // value (popped first)
                self.line(&format!("store_u{};", bits));
            }
            InstKind::Alloca { ty, count, align } => {
                let dest = inst.dest.as_deref().ok_or("alloca without result")?;
                if let Some(&off) = ctx.alloca_offsets.get(dest) {
                    // Static alloca: a fixed byte offset within the frame.
                    self.line(&format!("get_local {};", ctx.bp_slot));
                    if off != 0 {
                        self.push_int(off as i128, 64);
                        self.line("add_u64;");
                    }
                } else {
                    // Dynamic (runtime-count) alloca: bump the stack pointer.
                    self.gen_dynamic_alloca(ctx, ty, count.as_ref(), *align)?;
                }
                self.store_dest(ctx, Some(dest))?;
            }
            InstKind::GetElementPtr { base_ty, ptr, indices, .. } => {
                self.gen_gep(ctx, base_ty, ptr, indices)?;
                self.store_dest(ctx, inst.dest.as_deref())?;
            }
            InstKind::Call { callee, args, ret_ty, .. } => {
                // `@llvm.*` intrinsics are lowered inline (or to a syscall), not
                // called; everything else is an ordinary UVM call.
                match callee {
                    Value::Global(name) if name.starts_with("llvm.") => {
                        self.gen_intrinsic(ctx, inst.dest.as_deref(), name, ret_ty, args)?;
                    }
                    Value::Global(name) if name.starts_with("__uvm_") => {
                        self.gen_syscall(ctx, inst.dest.as_deref(), name, ret_ty, args)?;
                    }
                    // Float libm calls (`@sinf`, `@sqrtf`, ...) have no body in
                    // the module; lower them inline to UVM f32 ops.
                    Value::Global(name) if is_float_builtin(name) => {
                        self.gen_float_call(ctx, inst.dest.as_deref(), name, args)?;
                    }
                    // clang's optimizer can synthesize direct calls to the
                    // byte-compare libcalls bcmp/memcmp (e.g. when lowering
                    // `strcmp(x, "lit") == 0`), which have no body in the module.
                    // Route them to the UVM memcmp syscall: bcmp only needs the
                    // zero/non-zero distinction, which memcmp's result preserves.
                    Value::Global(name) if name == "bcmp" || name == "memcmp" => {
                        self.gen_memcmp_call(ctx, inst.dest.as_deref(), args)?;
                    }
                    _ => self.gen_call(ctx, inst.dest.as_deref(), callee, args)?,
                }
            }
            // Phi results are written on the predecessor edges, so the phi
            // instruction itself emits no code.
            InstKind::Phi { .. } => {}
            InstKind::AtomicLoad { ty, ptr } => {
                self.require_atomic_width(ty)?;
                self.push_value(ctx, ptr, 64)?;
                self.line("atomic_load_u64;");
                self.store_dest(ctx, inst.dest.as_deref())?;
            }
            InstKind::AtomicStore { ty, val, ptr } => {
                self.require_atomic_width(ty)?;
                self.push_value(ctx, ptr, 64)?; // address (popped second)
                self.push_value(ctx, val, 64)?; // value (popped first)
                self.line("atomic_store_u64;");
            }
            InstKind::AtomicRmw { op, ty, ptr, val } => {
                self.require_atomic_width(ty)?;
                self.gen_atomicrmw(ctx, *op, ptr, val, inst.dest.as_deref())?;
            }
            InstKind::Cmpxchg { ty, ptr, cmp, new } => {
                self.require_atomic_width(ty)?;
                self.gen_cmpxchg(ctx, ptr, cmp, new, inst.dest.as_deref())?;
            }
            InstKind::ExtractValue { agg, index } => {
                self.gen_extractvalue(ctx, agg, *index, inst.dest.as_deref())?;
            }
            // `freeze` turns poison/undef into an arbitrary but fixed concrete
            // value; for a well-defined operand it is the identity. Either way,
            // forwarding the operand's bit pattern to the result is correct.
            InstKind::Freeze { ty, val } => {
                let w = int_width(ty).unwrap_or((self.layout.size_of(ty) * 8) as u32);
                self.push_value(ctx, val, w)?;
                self.store_dest(ctx, inst.dest.as_deref())?;
            }
            // The UVM atomic ops carry their own ordering, so a standalone
            // fence needs no code.
            InstKind::Fence => {}
        }
        Ok(())
    }

    fn gen_bin(&mut self, ctx: &FnCtx, op: BinOp, ty: &Type, lhs: &Value, rhs: &Value) -> Result<(), String>
    {
        let w = int_width(ty)?;
        let ow = if w <= 32 { 32 } else { 64 };
        let signed = matches!(op, BinOp::SDiv | BinOp::SRem | BinOp::AShr);

        // lhs is always a value operand.
        self.push_value(ctx, lhs, w)?;
        if signed && w < ow {
            self.emit_sext(w, ow)?;
        }
        // rhs: a value for div/rem (sign-extend if signed); a shift count for shifts.
        self.push_value(ctx, rhs, w)?;
        if matches!(op, BinOp::SDiv | BinOp::SRem) && w < ow {
            self.emit_sext(w, ow)?;
        }

        self.line(&format!("{};", bin_mnemonic(op, ow)));

        // Re-establish the width invariant for sub-32-bit results.
        if w < 32 {
            self.emit_trunc_to(w);
        }
        Ok(())
    }

    /// Floating-point binary op → the corresponding UVM `*_f32`/`*_f64` op.
    fn gen_fbin(&mut self, ctx: &FnCtx, op: FBinOp, ty: &Type, lhs: &Value, rhs: &Value) -> Result<(), String>
    {
        let (sfx, w) = float_kind(ty)?;
        let base = match op {
            FBinOp::FAdd => "add",
            FBinOp::FSub => "sub",
            FBinOp::FMul => "mul",
            FBinOp::FDiv => "div",
            FBinOp::FRem => return Err("frem (floating-point remainder) is not supported (no UVM op)".into()),
        };
        self.push_value(ctx, lhs, w)?;
        self.push_value(ctx, rhs, w)?;
        self.line(&format!("{}_{};", base, sfx));
        Ok(())
    }

    /// `fneg x` = flip the IEEE sign bit (exact, incl. signed zero/NaN).
    fn gen_fneg(&mut self, ctx: &FnCtx, ty: &Type, val: &Value) -> Result<(), String>
    {
        let (_, w) = float_kind(ty)?;
        self.push_value(ctx, val, w)?;
        if w <= 32 {
            self.push_int(0x8000_0000, 32);
            self.line("xor_u32;");
        } else {
            self.push_int(0x8000_0000_0000_0000, 64);
            self.line("xor_u64;");
        }
        Ok(())
    }

    /// Floating-point compare. The UVM ops (`eq/ne/lt/le/gt/ge_f32` and the
    /// matching `_f64`) follow Rust semantics: the ordering compares are ordered
    /// (false on NaN), `eq` is ordered-equal, `ne` is unordered-not-equal. The
    /// remaining predicates are composed from those with a boolean complement /
    /// disjunction, which act on the 0/1 results and so are width-agnostic.
    fn gen_fcmp(&mut self, ctx: &FnCtx, pred: FCmpPred, ty: &Type, lhs: &Value, rhs: &Value) -> Result<(), String>
    {
        let (sfx, w) = float_kind(ty)?;
        let op = |name: &str| format!("{}_{}", name, sfx);
        use FCmpPred::*;
        match pred {
            False => self.line("push 0;"),
            True => self.line("push 1;"),
            // Ordered compares map directly.
            Oeq => self.fcmp_one(ctx, lhs, rhs, &op("eq"), w)?,
            Olt => self.fcmp_one(ctx, lhs, rhs, &op("lt"), w)?,
            Ole => self.fcmp_one(ctx, lhs, rhs, &op("le"), w)?,
            Ogt => self.fcmp_one(ctx, lhs, rhs, &op("gt"), w)?,
            Oge => self.fcmp_one(ctx, lhs, rhs, &op("ge"), w)?,
            // Unordered not-equal maps directly (Rust `!=`).
            Une => self.fcmp_one(ctx, lhs, rhs, &op("ne"), w)?,
            // Unordered inequalities = complement of the opposite ordered compare.
            Uge => { self.fcmp_one(ctx, lhs, rhs, &op("lt"), w)?; self.emit_not1(); }
            Ult => { self.fcmp_one(ctx, lhs, rhs, &op("ge"), w)?; self.emit_not1(); }
            Ugt => { self.fcmp_one(ctx, lhs, rhs, &op("le"), w)?; self.emit_not1(); }
            Ule => { self.fcmp_one(ctx, lhs, rhs, &op("gt"), w)?; self.emit_not1(); }
            // Ordered not-equal = (a<b) | (a>b).
            One => self.fcmp_or(ctx, lhs, rhs, &op("lt"), lhs, rhs, &op("gt"), w)?,
            // Unordered equal = !(ordered not-equal).
            Ueq => { self.fcmp_or(ctx, lhs, rhs, &op("lt"), lhs, rhs, &op("gt"), w)?; self.emit_not1(); }
            // Unordered (some NaN) = (a!=a) | (b!=b); ordered = its complement.
            Uno => self.fcmp_or(ctx, lhs, lhs, &op("ne"), rhs, rhs, &op("ne"), w)?,
            Ord => { self.fcmp_or(ctx, lhs, lhs, &op("ne"), rhs, rhs, &op("ne"), w)?; self.emit_not1(); }
        }
        Ok(())
    }

    /// Emit `push a; push b; <op>` for a single float compare of width `w`.
    fn fcmp_one(&mut self, ctx: &FnCtx, a: &Value, b: &Value, op: &str, w: u32) -> Result<(), String>
    {
        self.push_value(ctx, a, w)?;
        self.push_value(ctx, b, w)?;
        self.line(&format!("{};", op));
        Ok(())
    }

    /// Emit `(a1 <op1> b1) | (a2 <op2> b2)` for the composite fcmp predicates.
    /// The disjunction combines two i1 (0/1) results, so `or_u32` is correct
    /// regardless of the operand float width.
    fn fcmp_or(&mut self, ctx: &FnCtx, a1: &Value, b1: &Value, op1: &str, a2: &Value, b2: &Value, op2: &str, w: u32) -> Result<(), String>
    {
        self.fcmp_one(ctx, a1, b1, op1, w)?;
        self.fcmp_one(ctx, a2, b2, op2, w)?;
        self.line("or_u32;");
        Ok(())
    }

    /// Logically negate an i1 (0/1) on top of the stack.
    fn emit_not1(&mut self)
    {
        self.line("push 1;");
        self.line("xor_u32;");
    }

    /// Lower a libm call (`@sinf`/`@sin`, `@sqrtf`/`@sqrt`, `@powf`/`@pow`,
    /// `@fabsf`/`@fabs`, ...) to the matching UVM float op(s), inline. These have
    /// no body in the module, so this runs before the ordinary (would-be-
    /// undefined) call path. The `*f` names lower to f32 ops, the double-named
    /// ones to f64 ops.
    fn gen_float_call(&mut self, ctx: &FnCtx, dest: Option<&str>, name: &str, args: &[TypedVal]) -> Result<(), String>
    {
        match name {
            // Single-precision (f32).
            "sinf" => self.fmath1(ctx, args, "sin_f32", 32)?,
            "cosf" => self.fmath1(ctx, args, "cos_f32", 32)?,
            "tanf" => self.fmath1(ctx, args, "tan_f32", 32)?,
            "asinf" => self.fmath1(ctx, args, "asin_f32", 32)?,
            "acosf" => self.fmath1(ctx, args, "acos_f32", 32)?,
            "atanf" => self.fmath1(ctx, args, "atan_f32", 32)?,
            "sqrtf" => self.fmath1(ctx, args, "sqrt_f32", 32)?,
            "fabsf" => self.gen_fabs(ctx, &args[0].val, 32)?,
            "powf" => {
                self.push_value(ctx, &args[0].val, 32)?;
                self.push_value(ctx, &args[1].val, 32)?;
                self.line("pow_f32;");
            }
            // Double-precision (f64).
            "sin" => self.fmath1(ctx, args, "sin_f64", 64)?,
            "cos" => self.fmath1(ctx, args, "cos_f64", 64)?,
            "tan" => self.fmath1(ctx, args, "tan_f64", 64)?,
            "asin" => self.fmath1(ctx, args, "asin_f64", 64)?,
            "acos" => self.fmath1(ctx, args, "acos_f64", 64)?,
            "atan" => self.fmath1(ctx, args, "atan_f64", 64)?,
            "sqrt" => self.fmath1(ctx, args, "sqrt_f64", 64)?,
            "fabs" => self.gen_fabs(ctx, &args[0].val, 64)?,
            "pow" => {
                self.push_value(ctx, &args[0].val, 64)?;
                self.push_value(ctx, &args[1].val, 64)?;
                self.line("pow_f64;");
            }
            // clang canonicalizes `powf(2, x)`/`pow(2, x)` to `exp2f`/`exp2` at
            // -O1+; UVM has no exp2 op, so lower it back to `pow(2, x)`.
            "exp2f" => {
                self.push_float(2.0, 32);
                self.push_value(ctx, &args[0].val, 32)?;
                self.line("pow_f32;");
            }
            "exp2" => {
                self.push_float(2.0, 64);
                self.push_value(ctx, &args[0].val, 64)?;
                self.line("pow_f64;");
            }
            _ => return Err(format!("unsupported float library call @{}", name)),
        }
        self.store_dest(ctx, dest)
    }

    /// A one-argument float math op of width `w`: push the argument, emit `<op>`.
    fn fmath1(&mut self, ctx: &FnCtx, args: &[TypedVal], op: &str, w: u32) -> Result<(), String>
    {
        self.push_value(ctx, &args[0].val, w)?;
        self.line(&format!("{};", op));
        Ok(())
    }

    /// `fabs(x)` = clear the IEEE sign bit (width `w`: bit 31 for f32, bit 63 for
    /// f64).
    fn gen_fabs(&mut self, ctx: &FnCtx, x: &Value, w: u32) -> Result<(), String>
    {
        self.push_value(ctx, x, w)?;
        self.emit_fabs_top(w);
        Ok(())
    }

    /// fabs the float already on top of the stack (clear the IEEE sign bit).
    fn emit_fabs_top(&mut self, w: u32)
    {
        if w <= 32 {
            self.push_int(0x7fff_ffff, 32);
            self.line("and_u32;");
        } else {
            self.push_int(0x7fff_ffff_ffff_ffff, 64);
            self.line("and_u64;");
        }
    }

    /// `floor(x)` / `ceil(x)` (`is_ceil` selects). UVM has no rounding op, so the
    /// integral part is obtained by truncating toward zero through a
    /// float->int->float round trip, then adjusting by one when the truncation
    /// went the wrong way: floor subtracts 1 when it rounded up past x (t > x),
    /// ceil adds 1 when it rounded down below x (t < x).
    ///
    /// The round trip is only valid while the int conversion is exact and
    /// non-saturating. Every |x| >= 2^(mantissa bits) is already integral (and
    /// inf/NaN compare false against a finite bound), so a magnitude guard returns
    /// those inputs unchanged. Signed zero is not preserved (floor(-0.0) yields
    /// +0.0), a corner clang's own lowering also gives up on without SSE4.1.
    fn gen_floor_ceil(&mut self, ctx: &FnCtx, x: &Value, w: u32, is_ceil: bool) -> Result<(), String>
    {
        let sfx = if w <= 32 { "f32" } else { "f64" };
        // Smallest magnitude at/above which every value of this format is already
        // integral: 2^23 for f32 (below its 2^24 exact-int limit), 2^52 for f64.
        let intg = if w <= 32 { 8388608.0_f64 } else { 4503599627370496.0_f64 };
        let l_ret_x = self.fresh_label("rnd_ret_x");
        let l_no_adj = self.fresh_label("rnd_no_adj");
        let l_done = self.fresh_label("rnd_done");

        // Guard: only compute when |x| < 2^m; larger (incl. inf) and NaN are
        // returned unchanged, dodging the conversion's saturation/NaN->0.
        self.gen_fabs(ctx, x, w)?;
        self.push_float(intg, w);
        self.line(&format!("lt_{};", sfx));      // |x| < 2^m
        self.line(&format!("jz {};", l_ret_x));

        // cond = floor: t > x ; ceil: t < x, where t = (T)(int)x.
        self.emit_trunc_toward_zero(ctx, x, w)?; // t
        self.push_value(ctx, x, w)?;
        self.line(&format!("{}_{};", if is_ceil { "lt" } else { "gt" }, sfx));
        self.line(&format!("jz {};", l_no_adj));

        // Wrong-way truncation: floor -> t - 1, ceil -> t + 1.
        self.emit_trunc_toward_zero(ctx, x, w)?;
        self.push_float(1.0, w);
        self.line(&format!("{}_{};", if is_ceil { "add" } else { "sub" }, sfx));
        self.line(&format!("jmp {};", l_done));

        // Truncation already landed on the answer.
        self.line(&format!("{}:", l_no_adj));
        self.emit_trunc_toward_zero(ctx, x, w)?;
        self.line(&format!("jmp {};", l_done));

        // |x| >= 2^m, inf, or NaN: already integral.
        self.line(&format!("{}:", l_ret_x));
        self.push_value(ctx, x, w)?;
        self.line(&format!("{}:", l_done));
        Ok(())
    }

    /// Push `(T)(intN)x` — x truncated toward zero and back to float — via the
    /// UVM conversion pair (`f32_to_i32`/`i32_to_f32` or `f64_to_i64`/
    /// `i64_to_f64`). Exact only while |x| is below the format's exact-int limit;
    /// callers must guard larger magnitudes (the conversions saturate).
    fn emit_trunc_toward_zero(&mut self, ctx: &FnCtx, x: &Value, w: u32) -> Result<(), String>
    {
        self.push_value(ctx, x, w)?;
        if w <= 32 {
            self.line("f32_to_i32;");
            self.line("i32_to_f32;");
        } else {
            self.line("f64_to_i64;");
            self.line("i64_to_f64;");
        }
        Ok(())
    }

    /// `trunc(x)`: round toward zero. This is exactly the float->int->float round
    /// trip, guarded like `gen_floor_ceil`: only |x| below the format's exact-int
    /// limit is converted (the conversion saturates above it), so larger
    /// magnitudes, inf and NaN pass through unchanged (all already integral).
    fn gen_trunc(&mut self, ctx: &FnCtx, x: &Value, w: u32) -> Result<(), String>
    {
        let sfx = if w <= 32 { "f32" } else { "f64" };
        let intg = if w <= 32 { 8388608.0_f64 } else { 4503599627370496.0_f64 };
        let l_ret_x = self.fresh_label("trunc_ret_x");
        let l_done = self.fresh_label("trunc_done");

        self.gen_fabs(ctx, x, w)?;
        self.push_float(intg, w);
        self.line(&format!("lt_{};", sfx));       // |x| < 2^m
        self.line(&format!("jz {};", l_ret_x));

        self.emit_trunc_toward_zero(ctx, x, w)?;
        self.line(&format!("jmp {};", l_done));

        self.line(&format!("{}:", l_ret_x));
        self.push_value(ctx, x, w)?;
        self.line(&format!("{}:", l_done));
        Ok(())
    }

    /// `round(x)`: round to nearest, ties away from zero (C `round`/`@llvm.round`).
    /// Take the toward-zero integer part `t`, and bump it one further from zero
    /// (`t + copysign(1, x)`) when the discarded fraction is at least a half.
    /// Same magnitude guard as `gen_trunc`; signed zero is not preserved, matching
    /// the floor/ceil corner.
    fn gen_round(&mut self, ctx: &FnCtx, x: &Value, w: u32) -> Result<(), String>
    {
        let sfx = if w <= 32 { "f32" } else { "f64" };
        let intg = if w <= 32 { 8388608.0_f64 } else { 4503599627370496.0_f64 };
        let l_ret_x = self.fresh_label("round_ret_x");
        let l_no_adj = self.fresh_label("round_no_adj");
        let l_neg = self.fresh_label("round_neg");
        let l_done = self.fresh_label("round_done");

        // Guard: |x| >= 2^m (incl. inf) and NaN are already integral.
        self.gen_fabs(ctx, x, w)?;
        self.push_float(intg, w);
        self.line(&format!("lt_{};", sfx));       // |x| < 2^m
        self.line(&format!("jz {};", l_ret_x));

        // |x - t| < 0.5 ? -> keep t, else adjust.
        self.push_value(ctx, x, w)?;
        self.emit_trunc_toward_zero(ctx, x, w)?;  // t
        self.line(&format!("sub_{};", sfx));      // frac = x - t
        self.emit_fabs_top(w);                     // |frac|
        self.push_float(0.5, w);
        self.line(&format!("lt_{};", sfx));       // |frac| < 0.5
        self.line(&format!("jnz {};", l_no_adj));

        // Adjust away from zero: t + (x < 0 ? -1 : +1).
        self.emit_trunc_toward_zero(ctx, x, w)?;  // t
        self.push_value(ctx, x, w)?;
        self.push_float(0.0, w);
        self.line(&format!("lt_{};", sfx));       // x < 0
        self.line(&format!("jnz {};", l_neg));
        self.push_float(1.0, w);
        self.line(&format!("add_{};", sfx));
        self.line(&format!("jmp {};", l_done));
        self.line(&format!("{}:", l_neg));
        self.push_float(1.0, w);
        self.line(&format!("sub_{};", sfx));
        self.line(&format!("jmp {};", l_done));

        self.line(&format!("{}:", l_no_adj));
        self.emit_trunc_toward_zero(ctx, x, w)?;  // t
        self.line(&format!("jmp {};", l_done));

        self.line(&format!("{}:", l_ret_x));
        self.push_value(ctx, x, w)?;
        self.line(&format!("{}:", l_done));
        Ok(())
    }

    /// `fmin`/`fmax` (`@llvm.minnum`/`@llvm.maxnum`): IEEE-754 minNum/maxNum. If
    /// exactly one operand is NaN the other is returned; two NaNs give NaN. The
    /// +0/-0 tie is resolved by the ordered compare (which treats them as equal),
    /// so signed zero is not distinguished — the same corner as floor/ceil/round.
    fn gen_fminmax(&mut self, ctx: &FnCtx, x: &Value, y: &Value, w: u32, is_max: bool) -> Result<(), String>
    {
        let sfx = if w <= 32 { "f32" } else { "f64" };
        let l_ret_y = self.fresh_label("mm_ret_y");
        let l_ret_x = self.fresh_label("mm_ret_x");
        let l_lt = self.fresh_label("mm_lt");
        let l_done = self.fresh_label("mm_done");

        // x is NaN (x != x) -> return the other operand.
        self.push_value(ctx, x, w)?;
        self.push_value(ctx, x, w)?;
        self.line(&format!("ne_{};", sfx));
        self.line(&format!("jnz {};", l_ret_y));
        // y is NaN -> return x.
        self.push_value(ctx, y, w)?;
        self.push_value(ctx, y, w)?;
        self.line(&format!("ne_{};", sfx));
        self.line(&format!("jnz {};", l_ret_x));

        // Both finite/ordered: branch on x < y.
        self.push_value(ctx, x, w)?;
        self.push_value(ctx, y, w)?;
        self.line(&format!("lt_{};", sfx));
        self.line(&format!("jnz {};", l_lt));
        // x >= y: max -> x, min -> y.
        self.push_value(ctx, if is_max { x } else { y }, w)?;
        self.line(&format!("jmp {};", l_done));
        // x < y: max -> y, min -> x.
        self.line(&format!("{}:", l_lt));
        self.push_value(ctx, if is_max { y } else { x }, w)?;
        self.line(&format!("jmp {};", l_done));

        self.line(&format!("{}:", l_ret_y));
        self.push_value(ctx, y, w)?;
        self.line(&format!("jmp {};", l_done));
        self.line(&format!("{}:", l_ret_x));
        self.push_value(ctx, x, w)?;
        self.line(&format!("{}:", l_done));
        Ok(())
    }

    /// `copysign(x, y)` (`@llvm.copysign`): magnitude of `x` with the sign bit of
    /// `y`, i.e. `(x & ~signbit) | (y & signbit)`.
    fn gen_copysign(&mut self, ctx: &FnCtx, x: &Value, y: &Value, w: u32) -> Result<(), String>
    {
        self.push_value(ctx, x, w)?;
        if w <= 32 {
            self.push_int(0x7fff_ffff, 32);
            self.line("and_u32;");
        } else {
            self.push_int(0x7fff_ffff_ffff_ffff, 64);
            self.line("and_u64;");
        }
        self.push_value(ctx, y, w)?;
        if w <= 32 {
            self.push_int(0x8000_0000, 32);
            self.line("and_u32;");
            self.line("or_u32;");
        } else {
            self.push_int(0x8000_0000_0000_0000, 64);
            self.line("and_u64;");
            self.line("or_u64;");
        }
        Ok(())
    }

    fn gen_conv(&mut self, ctx: &FnCtx, op: ConvOp, from_ty: &Type, val: &Value, to_ty: &Type) -> Result<(), String>
    {
        match op {
            // integer -> float
            ConvOp::SIToFP | ConvOp::UIToFP => {
                let (sfx, _) = float_kind(to_ty)?;
                let fw = int_width(from_ty)?;
                self.push_value(ctx, val, fw)?;
                // Convert through i64: sign-extend the source for signed
                // conversion (unsigned is already zero-extended in the slot),
                // then let i64_to_f32/f64 round to nearest — matching native
                // sitofp/uitofp for all values in range.
                if op == ConvOp::SIToFP && fw < 64 {
                    self.emit_sext(fw, 64)?;
                }
                self.line(&format!("i64_to_{};", sfx));
            }
            // float -> integer (truncates toward zero, saturating; NaN -> 0).
            ConvOp::FPToSI | ConvOp::FPToUI => {
                let (sfx, fw) = float_kind(from_ty)?;
                let tw = int_width(to_ty)?;
                self.push_value(ctx, val, fw)?;
                if sfx == "f32" && tw <= 32 {
                    // f32_to_i32 sign-extends its i32 result into the 64-bit
                    // slot; re-truncate to restore the zero-extended invariant.
                    self.line("f32_to_i32;");
                    self.emit_trunc_to(tw);
                } else {
                    // Everything else goes through f64->i64: widen an f32 first,
                    // then narrow the i64 result to the target width.
                    if sfx == "f32" {
                        self.line("f32_to_f64;");
                    }
                    self.line("f64_to_i64;");
                    self.emit_trunc_to(tw);
                }
            }
            // float <-> double. UVM has no f64 *arithmetic*, but it can widen
            // and narrow between the two formats, which is enough to move a
            // `double` value through a `float` (used e.g. by printf's %f, which
            // narrows a double vararg to a float to format it). The result of a
            // widen is a 64-bit f64 pattern we can only move/store/narrow again.
            ConvOp::FPExt => {
                // float -> double (exact widening).
                self.push_value(ctx, val, 32)?;
                self.line("f32_to_f64;");
            }
            ConvOp::FPTrunc => {
                // double -> float (narrowing, round to nearest even).
                self.push_value(ctx, val, 64)?;
                self.line("f64_to_f32;");
            }
            // bitcast is representation-preserving: a float/double occupies the
            // low bits of the slot exactly like the same-width integer, so this
            // is a no-op beyond pushing the operand at its natural width. (The
            // int<->int / ptr<->int forms would also work via the width path
            // below, but handling every bitcast here lets float<->int through.)
            ConvOp::BitCast => {
                let w = scalar_width(from_ty)?;
                self.push_value(ctx, val, w)?;
            }
            // integer/pointer width conversions
            _ => {
                let fw = int_width(from_ty)?;
                let tw = int_width(to_ty)?;
                self.push_value(ctx, val, fw)?;
                self.emit_conv_op(op, fw, tw)?;
            }
        }
        Ok(())
    }

    /// Emit the width-adjusting op for a conversion whose operand is already on
    /// the stack (shared by instruction and constant-expression conversions).
    fn emit_conv_op(&mut self, op: ConvOp, fw: u32, tw: u32) -> Result<(), String>
    {
        match op {
            // trunc to a narrower width.
            ConvOp::Trunc => self.emit_trunc_to(tw),
            // The value is already zero-extended in its slot, so zext is free.
            ConvOp::ZExt => {}
            ConvOp::SExt => self.emit_sext(fw, tw)?,
            // Pointers are 64-bit ints; only width adjustment is needed.
            ConvOp::PtrToInt => {
                if tw < 64 {
                    self.emit_trunc_to(tw);
                }
            }
            ConvOp::IntToPtr => {} // zero-extend to 64-bit = no-op
            ConvOp::BitCast => {}  // same bits
            // The int<->float / float<->float casts are handled in gen_conv;
            // they never reach the constant-expression path.
            ConvOp::SIToFP | ConvOp::UIToFP | ConvOp::FPToSI
            | ConvOp::FPToUI | ConvOp::FPExt | ConvOp::FPTrunc => {
                return Err("floating-point conversion in a constant expression is not supported".into());
            }
        }
        Ok(())
    }

    // -- memory addressing ----------------------------------------------------

    /// Lower a `getelementptr` to address arithmetic: base + Σ index·stride,
    /// with constant contributions folded into a single added constant.
    fn gen_gep(&mut self, ctx: &FnCtx, base_ty: &Type, ptr: &Value, indices: &[TypedVal]) -> Result<(), String>
    {
        // Walk the indices, separating constant offset from variable terms.
        let mut const_off: i128 = 0;
        // (index value, index width, stride)
        let mut var_terms: Vec<(&Value, u32, u64)> = vec![];
        let mut cur_ty: Type = base_ty.clone();

        for (k, idx) in indices.iter().enumerate() {
            if k == 0 {
                // First index strides over the base type (pointer-as-array).
                let stride = self.layout.size_of(base_ty);
                match &idx.val {
                    Value::Int(c) => const_off += *c * stride as i128,
                    _ => var_terms.push((&idx.val, int_width(&idx.ty)?, stride)),
                }
            } else {
                match gep_step(&self.layout, &cur_ty, idx)? {
                    Step::Const(off, next) => {
                        const_off += off;
                        cur_ty = next;
                    }
                    Step::Var(stride, next) => {
                        var_terms.push((&idx.val, int_width(&idx.ty)?, stride));
                        cur_ty = next;
                    }
                }
            }
        }

        // Emit: base, then each variable term, then the constant.
        self.push_value(ctx, ptr, 64)?;
        for (val, w, stride) in &var_terms {
            self.push_value(ctx, val, *w)?;
            if *w < 64 {
                self.emit_sext(*w, 64)?; // GEP indices are signed
            }
            self.push_int(*stride as i128, 64);
            self.line("mul_u64;");
            self.line("add_u64;");
        }
        if const_off != 0 {
            self.push_int(const_off, 64);
            self.line("add_u64;");
        }
        Ok(())
    }

    fn emit_frame_leave(&mut self, ctx: &FnCtx)
    {
        // Restore the stack pointer to this frame's base (bp) in the thread-local
        // slot the prologue bumped. Stack-neutral: leaves any pending return value
        // already on the stack untouched. Resetting to bp reclaims the whole
        // frame, including any bytes a dynamic alloca bumped past it.
        if ctx.has_frame {
            self.line(&format!("get_local {};", ctx.bp_slot));
            self.line(&format!("thread_set {};", STACK_TLS_SLOT));
        }
    }

    /// Push the current software stack pointer (top of the alloca region, held in
    /// the thread-local slot STACK_TLS_SLOT) onto the operand stack.
    fn emit_sp_load(&mut self)
    {
        self.line(&format!("thread_get {};", STACK_TLS_SLOT));
    }

    /// Store the top-of-stack value as the new software stack pointer (into the
    /// thread-local slot STACK_TLS_SLOT). Consumes the value.
    fn emit_sp_store(&mut self)
    {
        self.line(&format!("thread_set {};", STACK_TLS_SLOT));
    }

    /// Lower a runtime-sized `alloca <ty>, <intty> <count>`: align the software
    /// stack pointer up to the allocation's alignment, hand that address back as
    /// the result, and bump the pointer past `count * sizeof(ty)` bytes. Leaves
    /// the (aligned) base address on the operand stack for the caller to store.
    ///
    /// The region lives until the function returns, when emit_frame_leave resets
    /// the stack pointer to the saved base — matching C's `alloca` lifetime. (An
    /// alloca in a loop therefore accumulates until return, exactly as on a
    /// native target; C99 VLAs get earlier reclaim via llvm.stackrestore.)
    fn gen_dynamic_alloca(&mut self, ctx: &FnCtx, ty: &Type, count: Option<&TypedVal>, align: Option<u64>) -> Result<(), String>
    {
        let elem_size = self.layout.size_of(ty);
        // Honor the IR's explicit alignment, else the element's natural one, but
        // never below 8 so the result suits any scalar and the stack pointer
        // stays word-aligned for the next allocation. LLVM guarantees a power of
        // two, so `sp & !(align-1)` after rounding up is the aligned address.
        let align = align.unwrap_or_else(|| self.layout.align_of(ty)).max(8);
        let mask = !(align - 1);

        // base = align_up(sp, align)
        self.emit_sp_load();                                 // [sp]
        self.push_int((align - 1) as i128, 64);
        self.line("add_u64;");                               // [sp + align-1]
        self.push_int(mask as i128, 64);
        self.line("and_u64;");                               // [base]
        self.line("dup;");                                   // [base, base]

        // new_sp = base + count * elem_size
        match count {
            None => self.push_int(1, 64),
            Some(tv) => self.push_value(ctx, &tv.val, 64)?,
        }                                                    // [base, base, count]
        if elem_size != 1 {
            self.push_int(elem_size as i128, 64);
            self.line("mul_u64;");                           // [base, base, size]
        }
        self.line("add_u64;");                               // [base, new_sp]
        self.emit_sp_store();                                // [base]
        Ok(())
    }

    /// Bit width of a scalar load/store (8/16/32/64).
    fn scalar_bits(&self, ty: &Type) -> Result<u32, String>
    {
        let bytes = self.layout.size_of(ty);
        match bytes {
            1 => Ok(8),
            2 => Ok(16),
            4 => Ok(32),
            8 => Ok(64),
            _ => Err(format!("load/store of non-scalar type {} ({} bytes)", type_str(ty), bytes)),
        }
    }

    // -- globals (.data) ------------------------------------------------------

    fn emit_global(&mut self, g: &'a Global) -> Result<(), String>
    {
        let label = sanitize(&g.name);
        let align = self.layout.align_of(&g.ty);
        let size = self.layout.size_of(&g.ty);
        self.line(&format!(".align {};", align));
        self.line(&format!("{}:", label));
        match &g.init {
            None => self.line(&format!(".zero {};", size)),
            Some(v) => self.emit_const_data(&label, 0, &g.ty, v)?,
        }
        self.line("");
        Ok(())
    }

    /// Emit the raw bytes of a constant initializer of `ty`, where the data
    /// lives at `offset` bytes into the global labelled `base`. Constant
    /// expressions (which can't be a static directive) reserve space and are
    /// stored at `base + offset` by startup code.
    fn emit_const_data(&mut self, base: &str, offset: u64, ty: &Type, val: &Value) -> Result<(), String>
    {
        match val {
            Value::Int(c) => {
                let bits = self.scalar_bits(ty)?;
                self.line(&format!(".u{} {};", bits, mask_to_width(*c, bits)));
            }
            Value::Float(f) => match ty {
                Type::Float => {
                    let f = *f as f32;
                    if f.is_finite() {
                        self.line(&format!(".f32 {};", fmt_f32(f)));
                    } else {
                        self.line(&format!(".u32 {};", f.to_bits()));
                    }
                }
                Type::Double => {
                    if f.is_finite() {
                        self.line(&format!(".f64 {};", fmt_f64(*f)));
                    } else {
                        self.line(&format!(".u64 {};", f.to_bits()));
                    }
                }
                _ => return Err(format!("float constant for non-float type {}", type_str(ty))),
            },
            Value::Null => self.line(".u64 0;"),
            Value::ZeroInit | Value::Undef | Value::Poison => {
                self.line(&format!(".zero {};", self.layout.size_of(ty)));
            }
            Value::CStr(bytes) => self.emit_hex_bytes(bytes),
            Value::Global(name) => self.line(&format!(".addr64 {};", sanitize(name))),
            Value::Array(elems) => {
                let mut o = offset;
                for e in elems {
                    self.emit_const_data(base, o, &e.ty, &e.val)?;
                    o += self.layout.size_of(&e.ty);
                }
            }
            Value::Struct(fields) => self.emit_struct_data(base, offset, ty, fields)?,
            Value::ConstExpr(ce) => {
                self.line(&format!(".zero {};", self.layout.size_of(ty)));
                self.runtime_inits.push((base.to_string(), offset, (**ce).clone()));
            }
            Value::Local(_) => return Err("local value in a constant initializer".into()),
        }
        Ok(())
    }

    /// Emit a struct constant, inserting padding so fields land at the offsets
    /// the layout computes.
    fn emit_struct_data(&mut self, base: &str, offset: u64, ty: &Type, fields: &[TypedVal]) -> Result<(), String>
    {
        let offsets: Vec<u64> = {
            let body = match ty {
                Type::Struct(b) => b,
                Type::NamedStruct(n) => self.layout.resolve(n),
                _ => return Err(format!("struct initializer for non-struct type {}", type_str(ty))),
            };
            (0..fields.len()).map(|i| self.layout.field_offset(body, i)).collect()
        };
        let total = self.layout.size_of(ty);
        let mut off = 0u64;
        for (i, f) in fields.iter().enumerate() {
            if offsets[i] > off {
                self.line(&format!(".zero {};", offsets[i] - off));
            }
            self.emit_const_data(base, offset + offsets[i], &f.ty, &f.val)?;
            off = offsets[i] + self.layout.size_of(&f.ty);
        }
        if total > off {
            self.line(&format!(".zero {};", total - off));
        }
        Ok(())
    }

    fn emit_hex_bytes(&mut self, bytes: &[u8])
    {
        if bytes.is_empty() {
            return;
        }
        let mut s = String::from(".hex ");
        for b in bytes {
            s.push_str(&format!("{:02x}", b));
        }
        s.push(';');
        self.line(&s);
    }

    // -- constant expressions (push the runtime value) ------------------------

    fn emit_const_expr(&mut self, ce: &ConstExpr) -> Result<(), String>
    {
        match ce {
            ConstExpr::GetElementPtr { base_ty, base, indices, .. } => {
                self.emit_const_value(&base.ty, &base.val)?;
                let off = const_gep_offset(&self.layout, base_ty, indices)?;
                if off != 0 {
                    self.push_int(off, 64);
                    self.line("add_u64;");
                }
            }
            ConstExpr::Conv { op, val, to } => {
                self.emit_const_value(&val.ty, &val.val)?;
                self.emit_conv_op(*op, int_width(&val.ty)?, int_width(to)?)?;
            }
            ConstExpr::Bin { op, lhs, rhs } => {
                self.emit_const_value(&lhs.ty, &lhs.val)?;
                self.emit_const_value(&rhs.ty, &rhs.val)?;
                let w = int_width(&lhs.ty)?;
                let ow = if w <= 32 { 32 } else { 64 };
                self.line(&format!("{};", bin_mnemonic(*op, ow)));
            }
        }
        Ok(())
    }

    fn emit_const_value(&mut self, ty: &Type, val: &Value) -> Result<(), String>
    {
        match val {
            Value::Int(c) => self.push_int(*c, int_width(ty).unwrap_or(64)),
            Value::Float(f) => self.push_float(*f, scalar_width(ty).unwrap_or(32)),
            Value::Null | Value::ZeroInit => self.line("push 0;"),
            Value::Global(name) => self.line(&format!("push {};", sanitize(name))),
            Value::ConstExpr(ce) => self.emit_const_expr(ce)?,
            _ => return Err(format!("unsupported constant value: {:?}", val)),
        }
        Ok(())
    }

    fn gen_icmp(&mut self, ctx: &FnCtx, pred: ICmpPred, ty: &Type, lhs: &Value, rhs: &Value) -> Result<(), String>
    {
        let w = int_width(ty)?;
        let ow = if w <= 32 { 32 } else { 64 };
        let signed = matches!(pred, ICmpPred::Sgt | ICmpPred::Sge | ICmpPred::Slt | ICmpPred::Sle);

        self.push_value(ctx, lhs, w)?;
        if signed && w < ow {
            self.emit_sext(w, ow)?;
        }
        self.push_value(ctx, rhs, w)?;
        if signed && w < ow {
            self.emit_sext(w, ow)?;
        }
        self.line(&format!("{};", icmp_mnemonic(pred, ow)));
        // Result is an i1 (0/1), already satisfying the width invariant.
        Ok(())
    }

    fn gen_select(&mut self, ctx: &FnCtx, cond: &Value, ty: &Type, tval: &Value, fval: &Value) -> Result<(), String>
    {
        let w = scalar_width(ty)?;
        let l_false = self.fresh_label("sel_false");
        let l_done = self.fresh_label("sel_done");

        self.push_value(ctx, cond, 1)?;
        self.line(&format!("jz {};", l_false));
        self.push_value(ctx, tval, w)?;
        self.line(&format!("jmp {};", l_done));
        self.line(&format!("{}:", l_false));
        self.push_value(ctx, fval, w)?;
        self.line(&format!("{}:", l_done));
        // The selected value is left on the stack for store_dest.
        Ok(())
    }

    // -- atomics --------------------------------------------------------------

    /// The UVM atomic ops (`atomic_load_u64` / `atomic_store_u64` /
    /// `atomic_cas_u64`) are all 64 bits wide, so atomics on narrower types
    /// (e.g. `_Atomic int`) are rejected rather than silently touching the
    /// adjacent bytes. Use a 64-bit atomic type instead.
    fn require_atomic_width(&self, ty: &Type) -> Result<(), String>
    {
        match self.layout.size_of(ty) {
            8 => Ok(()),
            n => Err(format!(
                "atomic operations are only supported on 64-bit types, got {} ({} bytes)",
                type_str(ty), n
            )),
        }
    }

    /// Lower `cmpxchg` to a single `atomic_cas_u64`. The CAS pushes the value
    /// found at the address; the swap succeeded iff that value equals `cmp`.
    /// The two aggregate fields are written into consecutive local slots:
    /// `base` (old value) and `base + 1` (success flag), where extractvalue
    /// reads them from.
    fn gen_cmpxchg(&mut self, ctx: &FnCtx, ptr: &Value, cmp: &Value, new: &Value, dest: Option<&str>) -> Result<(), String>
    {
        let name = dest.ok_or("cmpxchg without result")?;
        let base = *ctx.slots.get(name).ok_or_else(|| format!("no slot for %{}", name))?;

        // atomic_cas (addr) (cmp) (new) -> pushes the value read
        self.push_value(ctx, ptr, 64)?;
        self.push_value(ctx, cmp, 64)?;
        self.push_value(ctx, new, 64)?;
        self.line("atomic_cas_u64;");
        self.line("dup;");
        self.line(&format!("set_local {};", base)); // field 0 = old value
        // success = (old == cmp)
        self.push_value(ctx, cmp, 64)?;
        self.line("eq_u64;");
        self.line(&format!("set_local {};", base + 1)); // field 1 = success
        Ok(())
    }

    /// Read one field of a cmpxchg aggregate. Field 0 is the old value, field 1
    /// is the success flag; both live in the slots reserved by gen_cmpxchg.
    fn gen_extractvalue(&mut self, ctx: &FnCtx, agg: &Value, index: u32, dest: Option<&str>) -> Result<(), String>
    {
        let agg_name = match agg {
            Value::Local(n) => n,
            _ => return Err("extractvalue is only supported on cmpxchg results".into()),
        };
        let base = *ctx.slots.get(agg_name.as_str())
            .ok_or_else(|| format!("extractvalue references unknown value %{}", agg_name))?;
        let slot = match index {
            0 | 1 => base + index as usize,
            _ => return Err(format!(
                "extractvalue index {} out of range (only cmpxchg aggregates are supported)", index)),
        };
        self.line(&format!("get_local {};", slot));
        self.store_dest(ctx, dest)
    }

    /// Lower `llvm.umul.with.overflow.iN(a, b)` -> aggregate { iN product, i1 }.
    /// The two fields go into consecutive slots (like cmpxchg): field 0 is the
    /// low-N-bit product, field 1 the unsigned-overflow flag. Overflow is
    /// detected without a widening multiply: the product overflowed iff
    /// `a != 0 && product / a != b` (division by the nonzero operand recovers
    /// the other one only when nothing was lost). The `a == 0` case can't
    /// overflow and also guards against the trapping divide-by-zero.
    fn gen_umul_overflow(&mut self, ctx: &FnCtx, dest: Option<&str>, a: &TypedVal, b: &Value) -> Result<(), String>
    {
        let name = dest.ok_or("umul.with.overflow without result")?;
        let base = *ctx.slots.get(name).ok_or_else(|| format!("no slot for %{}", name))?;
        let w = int_width(&a.ty)?;
        if w != 32 && w != 64 {
            return Err(format!("umul.with.overflow only supported for i32/i64 (got i{})", w));
        }

        // field 0: product = a * b (low N bits)
        self.push_value(ctx, &a.val, w)?;
        self.push_value(ctx, b, w)?;
        self.line(&format!("mul_u{};", w));
        self.line("dup;");
        self.line(&format!("set_local {};", base));

        // field 1: overflow = (a != 0) && (product / a != b)
        let zero = self.fresh_label("umulov_zero");
        let done = self.fresh_label("umulov_done");
        self.push_value(ctx, &a.val, w)?;
        self.line(&format!("jz {};", zero));          // a == 0 -> no overflow
        self.line(&format!("get_local {};", base));   // product
        self.push_value(ctx, &a.val, w)?;
        self.line(&format!("div_u{};", w));           // product / a
        self.push_value(ctx, b, w)?;
        self.line(&format!("ne_u{};", w));            // (product / a) != b
        self.line(&format!("jmp {};", done));
        self.line(&format!("{}:", zero));
        self.line("push 0;");
        self.line(&format!("{}:", done));
        self.line(&format!("set_local {};", base + 1));
        Ok(())
    }

    /// Lower `atomicrmw` to a compare-and-swap retry loop. The result (the old
    /// value, held in the result slot) is what stays there when the CAS wins:
    ///
    /// ```text
    /// retry:  old  = atomic_load(ptr)
    ///         prev = atomic_cas(ptr, old, op(old, val))
    ///         if prev != old goto retry     # someone else won; try again
    /// ```
    fn gen_atomicrmw(&mut self, ctx: &FnCtx, op: RmwOp, ptr: &Value, val: &Value, dest: Option<&str>) -> Result<(), String>
    {
        let name = dest.ok_or("atomicrmw without result")?;
        let slot = *ctx.slots.get(name).ok_or_else(|| format!("no slot for %{}", name))?;
        let retry = self.fresh_label("armw_retry");

        self.line(&format!("{}:", retry));
        // old = atomic_load(ptr); keep it in the result slot
        self.push_value(ctx, ptr, 64)?;
        self.line("atomic_load_u64;");
        self.line(&format!("set_local {};", slot));
        // atomic_cas (addr) (cmp = old) (new = op(old, val)) -> pushes prev
        self.push_value(ctx, ptr, 64)?;
        self.line(&format!("get_local {};", slot)); // cmp = old
        self.emit_rmw_newval(ctx, op, slot, val)?;  // push op(old, val)
        self.line("atomic_cas_u64;");
        // retry while prev != old (the CAS lost a race)
        self.line(&format!("get_local {};", slot));
        self.line("eq_u64;");
        self.line(&format!("jz {};", retry));
        // The result (old value) is already in `slot`.
        Ok(())
    }

    /// Push `op(old, val)` given `old` in local `slot`. `xchg` ignores the old
    /// value; `nand` is `~(old & val)`, realized as an xor with all-ones.
    fn emit_rmw_newval(&mut self, ctx: &FnCtx, op: RmwOp, slot: usize, val: &Value) -> Result<(), String>
    {
        let bin = |g: &mut Self, mnem: &str, g_val: &Value| -> Result<(), String> {
            g.line(&format!("get_local {};", slot));
            g.push_value(ctx, g_val, 64)?;
            g.line(&format!("{};", mnem));
            Ok(())
        };
        match op {
            RmwOp::Xchg => self.push_value(ctx, val, 64)?,
            RmwOp::Add => bin(self, "add_u64", val)?,
            RmwOp::Sub => bin(self, "sub_u64", val)?,
            RmwOp::And => bin(self, "and_u64", val)?,
            RmwOp::Or => bin(self, "or_u64", val)?,
            RmwOp::Xor => bin(self, "xor_u64", val)?,
            RmwOp::Nand => {
                bin(self, "and_u64", val)?;
                self.push_int(-1, 64); // ~x == x ^ 0xFFFF_FFFF_FFFF_FFFF
                self.line("xor_u64;");
            }
        }
        Ok(())
    }

    // -- calls ----------------------------------------------------------------

    /// Lower a `call`. Arguments are pushed left-to-right (arg 0 first, so it
    /// lands at the callee's `get_arg 0`); varargs need no special handling —
    /// the caller just pushes every actual argument, fixed and variadic. A
    /// direct call names its label; an indirect call pushes the function
    /// pointer last (on top of the args) and uses `call_fp`. Every UVM call
    /// yields exactly one return value, bound to the result slot or discarded.
    fn gen_call(&mut self, ctx: &FnCtx, dest: Option<&str>, callee: &Value, args: &[TypedVal]) -> Result<(), String>
    {
        if args.len() > u8::MAX as usize {
            return Err(format!("call with {} args (> 255 not supported)", args.len()));
        }
        for a in args {
            let w = scalar_width(&a.ty)?;
            self.push_value(ctx, &a.val, w)?;
        }

        match callee {
            Value::Global(name) => {
                if !self.defined_fns.contains(name.as_str()) {
                    return Err(format!("call to undefined function @{} (external/intrinsic not yet supported)", name));
                }
                self.line(&format!("call {}, {};", sanitize(name), args.len()));
            }
            Value::Local(_) => {
                // Function pointer goes on top of the stack for call_fp.
                self.push_value(ctx, callee, 64)?;
                self.line(&format!("call_fp {};", args.len()));
            }
            other => return Err(format!("unsupported call target: {:?}", other)),
        }

        match dest {
            Some(name) => {
                let slot = *ctx.slots.get(name).ok_or_else(|| format!("no slot for %{}", name))?;
                self.line(&format!("set_local {};", slot));
            }
            None => self.line("pop;"),
        }
        Ok(())
    }

    /// Lower a call to a `__uvm_<name>` shim (declared by `<uvm/syscalls.h>`
    /// when compiled with clang) into an inline UVM `syscall <name>`. Arguments
    /// are pushed left-to-right; a value-returning syscall leaves one result on
    /// the stack, which we store into the destination slot (or discard).
    fn gen_syscall(&mut self, ctx: &FnCtx, dest: Option<&str>, sym: &str, ret_ty: &Type, args: &[TypedVal]) -> Result<(), String>
    {
        let name = &sym["__uvm_".len()..];
        for a in args {
            let w = scalar_width(&a.ty)?;
            self.push_value(ctx, &a.val, w)?;
        }
        self.line(&format!("syscall {};", name));

        // `void` syscalls push nothing; value syscalls leave exactly one result.
        if !matches!(ret_ty, Type::Void) {
            match dest {
                Some(d) => {
                    let slot = *ctx.slots.get(d).ok_or_else(|| format!("no slot for %{}", d))?;
                    self.line(&format!("set_local {};", slot));
                }
                None => self.line("pop;"),
            }
        }
        Ok(())
    }

    /// Lower an optimizer-synthesized `@bcmp` / `@memcmp` call to the UVM memcmp
    /// syscall. Both take `(ptr, ptr, size_t)` and return an int that is zero iff
    /// the byte ranges are equal (memcmp additionally orders; bcmp does not, but
    /// memcmp's value is a valid bcmp result).
    fn gen_memcmp_call(&mut self, ctx: &FnCtx, dest: Option<&str>, args: &[TypedVal]) -> Result<(), String>
    {
        for a in args {
            let w = scalar_width(&a.ty)?;
            self.push_value(ctx, &a.val, w)?;
        }
        self.line("syscall memcmp;");
        match dest {
            Some(d) => {
                let slot = *ctx.slots.get(d).ok_or_else(|| format!("no slot for %{}", d))?;
                self.line(&format!("set_local {};", slot));
            }
            None => self.line("pop;"),
        }
        Ok(())
    }

    // -- intrinsics -----------------------------------------------------------

    /// Lower an `@llvm.*` intrinsic. `memcpy`/`memset` map onto the native UVM
    /// syscalls; `lifetime.*` is dropped; the small arithmetic intrinsics
    /// expand inline to a handful of stack ops (no call, no runtime helper).
    /// The trailing metadata args LLVM passes (the `i1 volatile` on the memory
    /// intrinsics, the `i1 is_int_min_poison` on `abs`) are ignored.
    fn gen_intrinsic(&mut self, ctx: &FnCtx, dest: Option<&str>, name: &str, ret_ty: &Type, args: &[TypedVal]) -> Result<(), String>
    {
        let bare = &name["llvm.".len()..];

        // --- void intrinsics (no result) ---
        if bare.starts_with("lifetime.") {
            return Ok(()); // a scoping hint; emit nothing
        }
        if bare == "assume" {
            return Ok(()); // an optimizer hint (`llvm.assume(i1)`); no runtime effect.
                           // clang >=21 emits these for unrolled-loop trip counts.
        }
        if bare.starts_with("va_start") {
            return self.gen_va_start(ctx, &args[0].val);
        }
        if bare.starts_with("va_end") {
            return Ok(()); // nothing to tear down; the buffer lives in the frame
        }
        // Scoped stack save/restore, used by clang to reclaim C99 VLAs at the
        // end of their block: `stacksave` reads the software stack pointer and
        // `stackrestore` writes it back, freeing everything allocated since.
        if bare.starts_with("stacksave") {
            self.emit_sp_load();
            return self.store_dest(ctx, dest);
        }
        if bare.starts_with("stackrestore") {
            self.push_value(ctx, &args[0].val, 64)?;
            self.emit_sp_store();
            return Ok(());
        }
        if bare.starts_with("memcpy.") {
            // (dst, src, len, i1 volatile) -> UVM `memcpy(dst, src, num_bytes)`.
            self.push_value(ctx, &args[0].val, 64)?; // dst
            self.push_value(ctx, &args[1].val, 64)?; // src
            self.push_value(ctx, &args[2].val, 64)?; // num_bytes
            self.line("syscall memcpy;");
            return Ok(());
        }
        if bare.starts_with("memset.") {
            // (dst, i8 value, len, i1 volatile) -> UVM `memset(dst, value, num_bytes)`.
            self.push_value(ctx, &args[0].val, 64)?; // dst
            self.push_value(ctx, &args[1].val, 8)?;  // fill byte
            self.push_value(ctx, &args[2].val, 64)?; // num_bytes
            self.line("syscall memset;");
            return Ok(());
        }

        // --- aggregate-producing intrinsics ({ iN, i1 } into two slots) ---
        if bare.starts_with("umul.with.overflow.") {
            return self.gen_umul_overflow(ctx, dest, &args[0], &args[1].val);
        }

        // --- value-producing intrinsics ---
        let a = &args[0].val;
        if bare.starts_with("abs.") {
            self.gen_abs(ctx, a, ret_ty)?;
        } else if bare.starts_with("smax.") {
            self.gen_minmax(ctx, a, &args[1].val, ret_ty, true, true)?;
        } else if bare.starts_with("smin.") {
            self.gen_minmax(ctx, a, &args[1].val, ret_ty, false, true)?;
        } else if bare.starts_with("umax.") {
            self.gen_minmax(ctx, a, &args[1].val, ret_ty, true, false)?;
        } else if bare.starts_with("umin.") {
            self.gen_minmax(ctx, a, &args[1].val, ret_ty, false, false)?;
        } else if bare.starts_with("scmp.") {
            self.gen_three_way(ctx, a, &args[1].val, &args[0].ty, ret_ty, true)?;
        } else if bare.starts_with("ucmp.") {
            self.gen_three_way(ctx, a, &args[1].val, &args[0].ty, ret_ty, false)?;
        } else if bare.starts_with("usub.sat.") {
            self.gen_usub_sat(ctx, a, &args[1].val, ret_ty)?;
        } else if bare.starts_with("fshl.") {
            self.gen_funnel_shift(ctx, a, &args[1].val, &args[2].val, ret_ty, true)?;
        } else if bare.starts_with("fshr.") {
            self.gen_funnel_shift(ctx, a, &args[1].val, &args[2].val, ret_ty, false)?;
        } else if bare.starts_with("bitreverse.") {
            let w = int_width(ret_ty)?;
            if w != 8 {
                return Err(format!("llvm.bitreverse only supported for i8 (got i{})", w));
            }
            self.gen_bitreverse8(ctx, a)?;
        } else if bare.starts_with("ctpop.") {
            self.gen_ctpop(ctx, a, ret_ty)?;
        } else if bare.starts_with("ctlz.") {
            self.gen_ctlz(ctx, a, ret_ty)?;
        } else if bare.starts_with("cttz.") {
            self.gen_cttz(ctx, a, ret_ty)?;
        } else if bare.starts_with("sqrt.") {
            let (sfx, w) = float_kind(ret_ty)?;
            self.fmath1(ctx, args, &format!("sqrt_{}", sfx), w)?;
        } else if bare.starts_with("sin.") {
            let (sfx, w) = float_kind(ret_ty)?;
            self.fmath1(ctx, args, &format!("sin_{}", sfx), w)?;
        } else if bare.starts_with("cos.") {
            let (sfx, w) = float_kind(ret_ty)?;
            self.fmath1(ctx, args, &format!("cos_{}", sfx), w)?;
        } else if bare.starts_with("fabs.") {
            let (_, w) = float_kind(ret_ty)?;
            self.gen_fabs(ctx, a, w)?;
        } else if bare.starts_with("floor.") {
            let (_, w) = float_kind(ret_ty)?;
            self.gen_floor_ceil(ctx, a, w, false)?;
        } else if bare.starts_with("ceil.") {
            let (_, w) = float_kind(ret_ty)?;
            self.gen_floor_ceil(ctx, a, w, true)?;
        } else if bare.starts_with("trunc.") {
            let (_, w) = float_kind(ret_ty)?;
            self.gen_trunc(ctx, a, w)?;
        } else if bare.starts_with("round.") {
            let (_, w) = float_kind(ret_ty)?;
            self.gen_round(ctx, a, w)?;
        } else if bare.starts_with("minnum.") {
            let (_, w) = float_kind(ret_ty)?;
            self.gen_fminmax(ctx, a, &args[1].val, w, false)?;
        } else if bare.starts_with("maxnum.") {
            let (_, w) = float_kind(ret_ty)?;
            self.gen_fminmax(ctx, a, &args[1].val, w, true)?;
        } else if bare.starts_with("copysign.") {
            let (_, w) = float_kind(ret_ty)?;
            self.gen_copysign(ctx, a, &args[1].val, w)?;
        } else if bare.starts_with("pow.") {
            let (sfx, w) = float_kind(ret_ty)?;
            self.push_value(ctx, &args[0].val, w)?;
            self.push_value(ctx, &args[1].val, w)?;
            self.line(&format!("pow_{};", sfx));
        } else if bare.starts_with("fmuladd.") {
            // a*b + c with two roundings — UVM has no fused multiply-add. clang
            // targeting a baseline (no-FMA) machine lowers fmuladd the same way,
            // so this matches native there; on an FMA host the last bit can
            // differ (float tests compare with tolerance to absorb this).
            let (sfx, w) = float_kind(ret_ty)?;
            self.push_value(ctx, &args[0].val, w)?;
            self.push_value(ctx, &args[1].val, w)?;
            self.line(&format!("mul_{};", sfx));
            self.push_value(ctx, &args[2].val, w)?;
            self.line(&format!("add_{};", sfx));
        } else {
            return Err(format!("unsupported intrinsic @{}", name));
        }

        self.store_dest(ctx, dest)
    }

    /// Lower `llvm.va_start(ptr %ap)` by emulating the x86_64 SysV va_list.
    ///
    /// clang has already expanded every `va_arg` into ordinary IR that walks a
    /// `%struct.__va_list_tag { i32 gp_offset, i32 fp_offset, ptr overflow_area,
    /// ptr reg_save_area }`: an integer/pointer `va_arg` reads from
    /// `reg_save_area + gp_offset` while `gp_offset <= 40` (then advances it by
    /// 8), otherwise from `overflow_area` (advancing it by 8). So all we do here
    /// is materialize those two areas and seed the offsets; the walk itself is
    /// plain load/store/gep/br/phi that the back-end already handles.
    ///
    /// UVM keeps every actual argument (fixed + variadic) in the callee frame,
    /// indexable at runtime with `get_var_arg`. We copy them into one contiguous
    /// 8-byte-per-slot buffer `B` (so `B[i]` == argument `i`), bump-allocated from
    /// the stack-alloc region, then set:
    ///   * `reg_save_area   = B`        (indexed by gp_offset, seeded to `8*F`)
    ///   * `overflow_area   = B + 48`   (== `&B[6]`, where GP args 7.. would land)
    ///   * `gp_offset       = 8 * F`    (F = number of fixed named params)
    ///   * `fp_offset       = 48`       (FP varargs unsupported; see limitation)
    /// The first `va_arg` then reads `B[F]` (the first variadic arg) and each
    /// subsequent one advances exactly as the ABI walk expects, on either the
    /// in-register (`B[F..5]`) or in-memory (`B[6..]`) path.
    ///
    /// Limitation: only general-purpose (integer/pointer) variadic args are
    /// supported — a `double`/`float` `va_arg` uses the XMM save area indexed by
    /// `fp_offset`, which this does not build. That still covers printf's
    /// %d/%u/%x/%c/%s/%p.
    fn gen_va_start(&mut self, ctx: &FnCtx, ap: &Value) -> Result<(), String>
    {
        let (buf_slot, idx_slot) = ctx.va_scratch
            .ok_or("va_start in a function without reserved va scratch slots")?;

        // Bump-allocate an argc*8-byte buffer; save its base address in buf_slot.
        self.line("# llvm.va_start: build the x86_64 va_list register-save area");
        self.line("get_argc;");                          // [argc]
        self.line("push 3;");
        self.line("lshift_u64;");                        // [argc*8 = bytes]
        // Bump the thread's software stack pointer (thread-local slot) to reserve
        // `bytes`. [bytes] stays on the stack throughout; base is saved in buf_slot.
        self.line(&format!("thread_get {};", STACK_TLS_SLOT)); // [bytes, base]
        self.line("dup;");
        self.line(&format!("set_local {};", buf_slot));
        self.line("add_u64;");                       // [base + bytes]
        self.line(&format!("thread_set {};", STACK_TLS_SLOT));

        // Copy loop: for i in 0..argc { B[i] = get_var_arg(i) }.
        let l_cond = self.fresh_label("vastart_cond");
        let l_done = self.fresh_label("vastart_done");
        self.line("push 0;");
        self.line(&format!("set_local {};", idx_slot));  // i = 0
        self.line(&format!("{}:", l_cond));
        self.line(&format!("get_local {};", idx_slot));
        self.line("get_argc;");
        self.line("lt_u64;");
        self.line(&format!("jz {};", l_done));
        self.line(&format!("get_local {};", buf_slot));  // [base]
        self.line(&format!("get_local {};", idx_slot));
        self.line("push 3;");
        self.line("lshift_u64;");
        self.line("add_u64;");                           // [&B[i]]
        self.line(&format!("get_local {};", idx_slot));
        self.line("get_var_arg;");                       // [&B[i], arg_i]
        self.line("store_u64;");
        self.line(&format!("get_local {};", idx_slot));
        self.line("push 1;");
        self.line("add_u64;");
        self.line(&format!("set_local {};", idx_slot));  // i += 1
        self.line(&format!("jmp {};", l_cond));
        self.line(&format!("{}:", l_done));

        // Initialize the four __va_list_tag fields at %ap. Store order per the
        // Store lowering: push address, then value (value popped first).
        let gp_off = (ctx.num_params as i128) * 8;
        // gp_offset (i32 @ ap+0) = 8 * F
        self.push_value(ctx, ap, 64)?;
        self.push_int(gp_off, 32);
        self.line("store_u32;");
        // fp_offset (i32 @ ap+4) = 48 (the ABI's post-GP base; FP unsupported)
        self.push_value(ctx, ap, 64)?;
        self.line("push 4;");
        self.line("add_u64;");
        self.push_int(48, 32);
        self.line("store_u32;");
        // overflow_arg_area (ptr @ ap+8) = base + 48
        self.push_value(ctx, ap, 64)?;
        self.line("push 8;");
        self.line("add_u64;");
        self.line(&format!("get_local {};", buf_slot));
        self.line("push 48;");
        self.line("add_u64;");
        self.line("store_u64;");
        // reg_save_area (ptr @ ap+16) = base
        self.push_value(ctx, ap, 64)?;
        self.line("push 16;");
        self.line("add_u64;");
        self.line(&format!("get_local {};", buf_slot));
        self.line("store_u64;");
        Ok(())
    }

    /// `abs(x)` = `x < 0 ? -x : x`. INT_MIN wraps to itself, which matches the
    /// intrinsic's poison-on-INT_MIN contract (any result is acceptable there).
    fn gen_abs(&mut self, ctx: &FnCtx, x: &Value, ty: &Type) -> Result<(), String>
    {
        let w = int_width(ty)?;
        let ow = if w <= 32 { 32 } else { 64 };
        let l_neg = self.fresh_label("abs_neg");
        let l_done = self.fresh_label("abs_done");

        // cond = x < 0 (signed)
        self.push_value(ctx, x, w)?;
        if w < ow { self.emit_sext(w, ow)?; }
        self.push_int(0, ow);
        self.line(&format!("lt_i{};", ow));
        self.line(&format!("jnz {};", l_neg));

        // x >= 0: the value is x itself.
        self.push_value(ctx, x, w)?;
        self.line(&format!("jmp {};", l_done));

        // x < 0: 0 - x.
        self.line(&format!("{}:", l_neg));
        self.push_int(0, ow);
        self.push_value(ctx, x, w)?;
        self.line(&format!("sub_u{};", ow));
        if w < 32 { self.emit_trunc_to(w); }
        self.line(&format!("{}:", l_done));
        Ok(())
    }

    /// `min`/`max` of two operands via a compare + branch (the UVM `select` op
    /// indexes slots, not stack values, so it can't be used here).
    fn gen_minmax(&mut self, ctx: &FnCtx, a: &Value, b: &Value, ty: &Type, is_max: bool, signed: bool) -> Result<(), String>
    {
        let w = int_width(ty)?;
        let lt = if signed { ICmpPred::Slt } else { ICmpPred::Ult };
        self.gen_icmp(ctx, lt, ty, a, b)?; // cond = a < b
        let l_else = self.fresh_label("mm_else");
        let l_done = self.fresh_label("mm_done");
        self.line(&format!("jz {};", l_else));
        // a < b: max picks b, min picks a.
        self.push_value(ctx, if is_max { b } else { a }, w)?;
        self.line(&format!("jmp {};", l_done));
        self.line(&format!("{}:", l_else));
        // a >= b: max picks a, min picks b.
        self.push_value(ctx, if is_max { a } else { b }, w)?;
        self.line(&format!("{}:", l_done));
        Ok(())
    }

    /// Three-way compare (`scmp`/`ucmp`): `(a > b) - (a < b)` in {-1, 0, 1}.
    /// The compare uses the operand type `op_ty`; the result width is `ret_ty`.
    fn gen_three_way(&mut self, ctx: &FnCtx, a: &Value, b: &Value, op_ty: &Type, ret_ty: &Type, signed: bool) -> Result<(), String>
    {
        let (gt, lt) = if signed {
            (ICmpPred::Sgt, ICmpPred::Slt)
        } else {
            (ICmpPred::Ugt, ICmpPred::Ult)
        };
        self.gen_icmp(ctx, gt, op_ty, a, b)?; // g (0/1)
        self.gen_icmp(ctx, lt, op_ty, a, b)?; // l (0/1)  -> stack [g, l]
        let rw = int_width(ret_ty)?;
        let sw = if rw <= 32 { 32 } else { 64 };
        self.line(&format!("sub_u{};", sw)); // g - l  (wraps to -1 at the result width)
        if rw < 32 { self.emit_trunc_to(rw); }
        Ok(())
    }

    /// Unsigned saturating subtract: `a > b ? a - b : 0`.
    fn gen_usub_sat(&mut self, ctx: &FnCtx, a: &Value, b: &Value, ty: &Type) -> Result<(), String>
    {
        let w = int_width(ty)?;
        let ow = if w <= 32 { 32 } else { 64 };
        self.gen_icmp(ctx, ICmpPred::Ugt, ty, a, b)?; // cond = a > b
        let l_zero = self.fresh_label("usat_zero");
        let l_done = self.fresh_label("usat_done");
        self.line(&format!("jz {};", l_zero));
        self.push_value(ctx, a, w)?;
        self.push_value(ctx, b, w)?;
        self.line(&format!("sub_u{};", ow));
        if w < 32 { self.emit_trunc_to(w); }
        self.line(&format!("jmp {};", l_done));
        self.line(&format!("{}:", l_zero));
        self.line("push 0;");
        self.line(&format!("{}:", l_done));
        Ok(())
    }

    /// Lower a funnel shift `llvm.fshl.iN` / `llvm.fshr.iN` (`is_left` selects
    /// which). A funnel shift concatenates `a` (high) and `b` (low) into a
    /// `2N`-bit value and shifts by `c mod N`, keeping the high N bits (`fshl`)
    /// or low N bits (`fshr`); with `a == b` it is a rotate. clang emits these
    /// for byte rotates. Integer widths are powers of two, so `c mod N` is
    /// `c & (N-1)`.
    fn gen_funnel_shift(
        &mut self,
        ctx: &FnCtx,
        a: &Value,
        b: &Value,
        c: &Value,
        ty: &Type,
        is_left: bool,
    ) -> Result<(), String>
    {
        let dir = if is_left { "l" } else { "r" };
        let w = int_width(ty)?;
        if !matches!(w, 8 | 16 | 32 | 64) {
            return Err(format!("llvm.fsh{} only supported for i8/i16/i32/i64 (got i{})", dir, w));
        }
        // The shift amount is a compile-time constant in the IR clang emits (a
        // rotate by a fixed distance); a runtime distance would need the operand
        // duplicated across three shifts, which we don't have a use for.
        let cv = match c {
            Value::Int(cv) => *cv,
            _ => return Err(format!("llvm.fsh{} with a non-constant shift amount is not supported", dir)),
        };
        let s = (cv & (w as i128 - 1)) as u32;

        // s == 0 keeps no bits from the other operand: fshl is `a`, fshr is `b`.
        if s == 0 {
            return self.push_value(ctx, if is_left { a } else { b }, w);
        }

        // result = (a << la) | (b >> ra), then narrow to N bits. Both amounts
        // are in 1..=N-1 (< 64), so neither shift is out of range even for i64.
        let (la, ra) = if is_left { (s, w - s) } else { (w - s, s) };
        self.push_value(ctx, a, w)?;
        self.push_int(la as i128, 64);
        self.line("lshift_u64;");
        self.push_value(ctx, b, w)?;
        self.push_int(ra as i128, 64);
        self.line("rshift_u64;");
        self.line("or_u64;");
        self.emit_trunc_to(w); // normalize to a valid iN slot
        Ok(())
    }

    /// Reverse the bits of a byte with the classic branchless 64-bit trick:
    /// `((b * 0x0202020202) & 0x010884422010) % 1023`.
    fn gen_bitreverse8(&mut self, ctx: &FnCtx, x: &Value) -> Result<(), String>
    {
        self.push_value(ctx, x, 8)?;
        self.push_int(0x0202020202, 64);
        self.line("mul_u64;");
        self.push_int(0x010884422010, 64);
        self.line("and_u64;");
        self.push_int(1023, 64);
        self.line("mod_u64;"); // result is 0..255, already a valid i8 slot
        Ok(())
    }

    /// Emit the native popcount op for a value of width `w` sitting on the stack
    /// (`popcnt_i32` counts the low 32 bits, `popcnt_i64` all 64). The operand is
    /// zero-extended in its slot, so the narrow op counts exactly the `w` bits.
    fn emit_popcnt(&mut self, w: u32)
    {
        self.line(if w <= 32 { "popcnt_i32;" } else { "popcnt_i64;" });
    }

    /// `llvm.ctpop.iN` — population count. One native instruction: the operand is
    /// zero-extended in its slot, so its padding bits contribute no set bits.
    fn gen_ctpop(&mut self, ctx: &FnCtx, x: &Value, ty: &Type) -> Result<(), String>
    {
        let w = int_width(ty)?;
        if w > 64 {
            return Err(format!("llvm.ctpop only supported up to i64 (got i{})", w));
        }
        self.push_value(ctx, x, w)?;
        self.emit_popcnt(w);
        Ok(())
    }

    /// `llvm.ctlz.iN` — count leading zeros. UVM has no clz, so smear every bit
    /// below the most-significant set bit down to bit 0, popcount that (= the MSB
    /// index + 1 = number of significant bits), and subtract from N. Zero smears
    /// to zero, giving popcount 0 and result N — the value ctlz defines at zero.
    /// (The `is_zero_poison` operand is irrelevant: N refines poison.)
    fn gen_ctlz(&mut self, ctx: &FnCtx, x: &Value, ty: &Type) -> Result<(), String>
    {
        let w = int_width(ty)?;
        if w > 64 {
            return Err(format!("llvm.ctlz only supported up to i64 (got i{})", w));
        }
        self.push_value(ctx, x, w)?;
        // x |= x>>1 |= x>>2 |= ... — only distances < w matter (the operand is
        // zero-extended, so wider shifts would just OR in zeros).
        let mut s = 1;
        while s < w {
            self.line("dup;");
            self.push_int(s as i128, 64);
            self.line("rshift_u64;");
            self.line("or_u64;");
            s <<= 1;
        }
        self.emit_popcnt(w);        // number of significant bits
        self.push_int(w as i128, 64);
        self.line("swap;");
        self.line("sub_u64;");      // N - significant_bits
        Ok(())
    }

    /// `llvm.cttz.iN` — count trailing zeros, as `popcount(~x & (x-1))` masked to
    /// N bits. `~x & (x-1)` is the run of trailing zeros below the lowest set bit;
    /// for x == 0 it is all-ones and the mask makes the count N, as cttz defines.
    /// (The `is_zero_poison` operand is irrelevant: N refines poison.)
    fn gen_cttz(&mut self, ctx: &FnCtx, x: &Value, ty: &Type) -> Result<(), String>
    {
        let w = int_width(ty)?;
        if w > 64 {
            return Err(format!("llvm.cttz only supported up to i64 (got i{})", w));
        }
        self.push_value(ctx, x, w)?;   // [x]
        self.line("dup;");             // [x, x]
        self.push_int(1, 64);
        self.line("sub_u64;");         // [x, x-1]
        self.line("swap;");            // [x-1, x]
        self.line("not_u64;");         // [x-1, ~x]
        self.line("and_u64;");         // [(x-1) & ~x]
        if w < 64 {
            self.push_int((1i128 << w) - 1, 64);
            self.line("and_u64;");     // mask to N bits (x==0 -> N)
        }
        self.emit_popcnt(w);
        Ok(())
    }

    // -- terminators ----------------------------------------------------------

    fn gen_term(&mut self, ctx: &FnCtx, pred: &str, term: &Terminator) -> Result<(), String>
    {
        match term {
            Terminator::Ret { val } => match val {
                None => {
                    // `ret void`: UVM `ret` always returns a value, push 0.
                    self.line("push 0;");
                    self.emit_frame_leave(ctx);
                    self.line("ret;");
                }
                Some(tv) => {
                    let w = scalar_width(&tv.ty)?;
                    self.push_value(ctx, &tv.val, w)?;
                    self.emit_frame_leave(ctx);
                    self.line("ret;");
                }
            },

            Terminator::Br { cond: None, if_true, .. } => {
                self.emit_edge_copies(ctx, pred, if_true)?;
                self.line(&format!("jmp {};", block_label(&ctx.name, if_true)));
            }

            Terminator::Br { cond: Some(c), if_true, if_false } => {
                let if_false = if_false.as_deref().ok_or("conditional br missing false target")?;
                // Each branch edge gets its own phi-copy sequence, which makes
                // critical edges correct without an explicit splitting pass.
                self.push_value(ctx, c, 1)?;
                let l_false = self.fresh_label("br_false");
                self.line(&format!("jz {};", l_false));
                self.emit_edge_copies(ctx, pred, if_true)?;
                self.line(&format!("jmp {};", block_label(&ctx.name, if_true)));
                self.line(&format!("{}:", l_false));
                self.emit_edge_copies(ctx, pred, if_false)?;
                self.line(&format!("jmp {};", block_label(&ctx.name, if_false)));
            }

            Terminator::Switch { ty, val, default, cases } => {
                let w = int_width(ty)?;
                let ow = if w <= 32 { 32 } else { 64 };
                let mut case_targets = Vec::with_capacity(cases.len());
                for (cv, target) in cases {
                    let l_case = self.fresh_label("sw_case");
                    self.push_value(ctx, val, w)?;
                    self.push_int(*cv, w);
                    self.line(&format!("eq_u{};", ow));
                    self.line(&format!("jnz {};", l_case));
                    case_targets.push((l_case, target));
                }
                // Fall through to the default edge.
                self.emit_edge_copies(ctx, pred, default)?;
                self.line(&format!("jmp {};", block_label(&ctx.name, default)));
                // Then the per-case edges.
                for (l_case, target) in case_targets {
                    self.line(&format!("{}:", l_case));
                    self.emit_edge_copies(ctx, pred, target)?;
                    self.line(&format!("jmp {};", block_label(&ctx.name, target)));
                }
            }

            Terminator::Unreachable => self.line("panic;"),
        }
        Ok(())
    }

    /// Emit the phi assignments for the edge `pred -> succ_label`, as a parallel
    /// copy (push all incoming values, then store them into the phi slots in
    /// reverse, so all reads happen before any writes).
    fn emit_edge_copies(&mut self, ctx: &FnCtx, pred: &str, succ_label: &str) -> Result<(), String>
    {
        let succ = match ctx.blocks.get(succ_label) {
            Some(b) => *b,
            None => return Err(format!("branch to unknown block %{}", succ_label)),
        };

        let mut copies: Vec<(usize, &Value, &Type)> = vec![];
        for inst in &succ.insts {
            match &inst.kind {
                InstKind::Phi { ty, incoming } => {
                    let dest = inst.dest.as_deref().ok_or("phi without result name")?;
                    let slot = *ctx
                        .slots
                        .get(dest)
                        .ok_or_else(|| format!("no slot for phi %{}", dest))?;
                    let val = incoming
                        .iter()
                        .find(|(_, p)| p == pred)
                        .map(|(v, _)| v)
                        .ok_or_else(|| format!("phi %{} has no incoming value for predecessor %{}", dest, pred))?;
                    copies.push((slot, val, ty));
                }
                // Phis are only at the start of a block.
                _ => break,
            }
        }

        for (_, val, ty) in &copies {
            let w = scalar_width(ty)?;
            self.push_value(ctx, val, w)?;
        }
        for (slot, _, _) in copies.iter().rev() {
            self.line(&format!("set_local {};", slot));
        }
        Ok(())
    }

    fn fresh_label(&mut self, hint: &str) -> String
    {
        let n = self.label_counter;
        self.label_counter += 1;
        format!("__{}_{}", hint, n)
    }

    // -- operands -------------------------------------------------------------

    /// Push a value operand (of the given bit width) onto the stack.
    fn push_value(&mut self, ctx: &FnCtx, val: &Value, width: u32) -> Result<(), String>
    {
        match val {
            Value::Local(name) => {
                if let Some(&idx) = ctx.params.get(name.as_str()) {
                    self.line(&format!("get_arg {};", idx));
                } else if let Some(&slot) = ctx.slots.get(name.as_str()) {
                    self.line(&format!("get_local {};", slot));
                } else {
                    return Err(format!("undefined value %{} in {}", name, ctx.name));
                }
            }
            Value::Int(v) => self.push_int(*v, width),
            Value::Float(f) => self.push_float(*f, width),
            Value::Null => self.line("push 0;"),
            Value::Undef | Value::Poison | Value::ZeroInit => self.line("push 0;"),
            // The address of a global or function (both are plain labels).
            Value::Global(name) => self.line(&format!("push {};", sanitize(name))),
            Value::ConstExpr(ce) => self.emit_const_expr(ce)?,
            other => return Err(format!("codegen: operand not yet implemented: {:?}", other)),
        }
        Ok(())
    }

    /// Push an integer constant as its zero-extended `width`-bit pattern, so the
    /// slot satisfies the representation invariant.
    fn push_int(&mut self, v: i128, width: u32)
    {
        self.line(&format!("push {};", mask_to_width(v, width)));
    }

    /// Push a floating-point constant. A float/double occupies the low 32/64
    /// bits of the slot as its IEEE-754 pattern, so `push_f32`/`push_f64
    /// <decimal>` is exact for finite values (Rust's shortest form round-trips
    /// and the UVM assembler accepts it). Non-finite values (inf/NaN), whose
    /// decimal form the assembler's `parse_float` can't read, fall back to
    /// pushing the raw bit pattern as an integer — same slot contents, always
    /// assemblable.
    fn push_float(&mut self, v: f64, width: u32)
    {
        if width <= 32 {
            let f = v as f32;
            if f.is_finite() {
                self.line(&format!("push_f32 {};", fmt_f32(f)));
            } else {
                self.line(&format!("push {};", f.to_bits() as u64));
            }
        } else if v.is_finite() {
            self.line(&format!("push_f64 {};", fmt_f64(v)));
        } else {
            self.line(&format!("push {};", v.to_bits()));
        }
    }

    fn store_dest(&mut self, ctx: &FnCtx, dest: Option<&str>) -> Result<(), String>
    {
        match dest {
            Some(name) => {
                let slot = *ctx.slots.get(name).ok_or_else(|| format!("no slot for %{}", name))?;
                self.line(&format!("set_local {};", slot));
                Ok(())
            }
            None => Err("value-producing instruction has no result name".to_string()),
        }
    }

    // -- width adjustment -----------------------------------------------------

    /// Sign-extend the top-of-stack value from `from` bits to `to` bits.
    fn emit_sext(&mut self, from: u32, to: u32) -> Result<(), String>
    {
        // Direct ops: sx_i{8,16,32}_i{32,64}. For an intermediate width we
        // sign-extend to 32 or 64 and then truncate.
        let mid = if to <= 32 { 32 } else { 64 };
        if from == 1 {
            // Sign-extend a boolean: the i1 is 0 or 1, and the result is 0 or
            // all-ones (-1) at the target width. Isolate the low bit, then
            // multiply by an all-ones mask of width `to` (0*mask = 0,
            // 1*mask = mask = -1 at that width). The product occupies exactly
            // `to` bits, matching the convention that a width-`to` value has
            // its upper bits cleared.
            let mask = if to >= 64 { u64::MAX } else { (1u64 << to) - 1 };
            self.line("push 1;");
            self.line(&format!("and_u{};", mid));
            self.line(&format!("push {};", mask));
            self.line(&format!("mul_u{};", mid));
            return Ok(());
        }
        if (from == 8 || from == 16 || from == 32) && from < mid {
            self.line(&format!("sx_i{}_i{};", from, mid));
            if to < mid {
                self.emit_trunc_to(to);
            }
            Ok(())
        } else {
            Err(format!("unsupported sign extension i{} -> i{}", from, to))
        }
    }

    /// Truncate the top-of-stack value to `w` bits (clearing the upper bits).
    fn emit_trunc_to(&mut self, w: u32)
    {
        match w {
            1 => {
                self.line("push 1;");
                self.line("and_u32;");
            }
            8 => self.line("trunc_u8;"),
            16 => self.line("trunc_u16;"),
            32 => self.line("trunc_u32;"),
            _ => {} // 64: nothing to do
        }
    }

    // -- output ---------------------------------------------------------------

    fn line(&mut self, s: &str)
    {
        self.buf.push(s.to_string());
    }

    /// Commit the current scope's buffered lines to `out`, running the local
    /// round-trip peephole first. Called at each function boundary so slot
    /// numbers (which restart per function) are counted within one scope.
    fn flush_scope(&mut self)
    {
        let lines = std::mem::take(&mut self.buf);
        let lines = peephole_locals(lines);
        let lines = strip_fallthrough_jumps(lines);
        for l in lines {
            self.out.push_str(&l);
            self.out.push('\n');
        }
    }
}

